-- =============================================================================
--  Luminosa/WagLib/boot.lua
--
--  引导期启动配置（视口）。
--
--  【2026-11-18 改定：它不再是 on_game_init 的钩体】
--      旧说法把 boot.lua 认作 on_game_init 的实现，而项目层要到步骤 5 才装载
--      ⇒ 作者写的 `GameInit` 永远来不及存在（死代码）。
--      现在两件事分开：
--        · boot.lua   = **引导期配置**（视口）—— 只能用引擎原语
--        · on_game_init = **作者的初始化** —— 在步骤 5.7（层装载完成后）由 init.lua 调
--
--  【它与 init.lua 不是一回事】
--      init.lua  是**入口** —— 引擎按路径读取的第一个脚本，它编排整个启动次序。
--      boot.lua  是**启动配置的一步**。两个名字各归其位。
--
--  【它运行在用户词汇装载之前 —— 因此只能用引擎原语】
--      这不是限制，而是装载次序的自然结果：
--        映射层要读它设定的配置 ⇒ 它必须在映射层之前
--      ⇒ 于是它里面写的是 wag.space.set_viewport{...}，
--        而不是 SetViewPort{...} 这类映射出来的名字。
--
--  【13 个槽永远有实现】
--      步骤 0 由引擎预置成空函数 ⇒ "引擎调用时槽不是函数"那条
--      引擎内部错误在实际运行中几乎不可能触发。
--
--  【保证被调用与被保证不被调用的】
--      13 个钩子全部有调用点（2026-11-18 起）；但 on_game_exit **不保证**被调用
--      （强杀、崩溃时没有机会）。
-- =============================================================================

local M = {}

--- 项目在这一步设定的配置。
--
-- 【为什么配置是一张表，而不是一堆直接写在 run() 里的调用】
--   因为这样"项目要设什么"与"用什么名字写"就被分开了：
--     · 这张表可以被项目侧覆盖（在映射层装载之后，那时用户词汇已经可用）
--     · 而 run() 本身只负责"把表交给引擎"
--   ⇒ 于是"定制"不需要重写 boot 的逻辑，只需要填表。
--
-- 【为什么这里只有视口一项】
--   因为 boot 只负责“必须在映射层之前定下来”的启动配置；
--   音频、输入、资源加载各有自己的初始化/装配路径，不在这张表里。
-- 【窗口尺寸不在这里】
--   lumi.screen 要到步骤 4.5 才装配，而 boot 在步骤 3。
--   项目若要在启动时选窗口尺寸，应在 on_game_init 里调用
--   lumi.screen.choose(...)，不要往 boot 表里加一个读不到的字段。
M.config = {
    -- -------------------------------------------------------------------------
    --  视口
    -- -------------------------------------------------------------------------
    --
    -- 【为什么这是必须设的一项】
    --   默认视口是 1920 × 1080、信箱策略。而"世界的可见范围"是这个项目的
    --   设计决定，不是引擎能猜的。所以它应当在启动时被显式设定 ——
    --   或者被显式地留在默认值上（那也是一个决定）。
    --
    -- 【已定的三条规则】
    --   · render   **可省略**（表示保持不变）
    --   · strategy **不可省略**，省略即报错
    --   · strategy 的取值区分大小写；未定义的值报错（不回落）
    --
    -- 【一组对称但不同义的规则 —— 这里解释为什么】
    --   render   是**参数**（省略 = 不变，合法）
    --   strategy 是**"这个调用在做什么"**（省略 = 报错）
    --
    --   若 strategy 可以省略并默认为某种策略，那么"我只想改 render"与
    --   "我想同时改策略但我忘了写"这两种意图就无法区分。
    viewport = {
        -- 世界的可见范围，单位是项目逻辑单位（不是窗口尺寸）。
        --
        -- 【以**逻辑原点**为中心】逻辑坐标的原点在窗口中心，所以 render 的
        -- 左下角是 (−w/2, −h/2)。于是逻辑点 (0,0) 落在屏幕中心。
        --
        -- 若写成 l = 0, b = 0，那么 (0,0) 会落在"可见区域的左下角" ——
        -- 那会让所有内容的位置依 render 的尺寸而漂移。
        --
        -- =====================================================================
        --  【与引擎 C++ 默认一致：1920×1080、16:9】
        -- =====================================================================
        --
        -- 当前运行默认与 C++ 构造函数的 1920×1080 一致：
        --   · 窗口默认 1920×1080 ⇒ letterbox 下 dst.b = 0，没有上下黑边
        --   · 第一帧到第二帧不再因为 render 比例不同而跳变
        --
        -- 【旧值 1920×810 的来历】
        --   它曾用来**故意制造上下 135px 黑边**，验证 dst.b 的双重身份
        --   （《坐标系链条》6.2.12）。这是开发期脚手架，不是游戏设计尺寸。
        --   现在默认全窗口后，这条验证不再靠默认场景进行。
        --
        -- 【窗口被拖成非 16:9 时】
        --   仍用 letterbox：保持 16:9、上下或左右出现黑边，不拉伸画面。
        --   若项目希望永远铺满（允许变形），可在 on_game_init 里显式
        --   调用 wag.space.set_viewport(..., "stretch")。
        -- =====================================================================
        render = { l = -960, b = -540, w = 1920, h = 1080 },

        -- 宽高比不匹配时的处理。
        --   "letterbox" —— 保持 render 的设计尺寸，外面不画（黑边）
        --   "stretch"   —— 把 render 铺满窗口，比例不一致时画面被拉伸
        strategy = "letterbox",
    },
}

--- 执行初始化。
--
-- 【调用点】init.lua 的步骤 3。
--
-- 【它为什么不做错处理】
--   因为它调用的引擎原语**自己会报错**：非法参数在跨边界处被拒绝并终止。
--   在脚本侧再包一层 pcall 会把"数据矛盾"变成"静默忽略"，而那是引擎
--   刻意不做的（引擎只判断数据是否矛盾，不做兜底）。
function M.run()
    -- -------------------------------------------------------------------------
    --  设定视口
    -- -------------------------------------------------------------------------
    --
    -- 【注意：这里用的是引擎原语 wag.space.set_viewport】
    --   不是映射层提供的名字。理由见文件头。
    --
    -- 【若项目想要不同的视口】
    --   它有两种正当做法：
    --     ① 在 on_game_init（步骤 5.7）里用用户词汇 / 原语再调一次 set_viewport
    --     ② 在更晚的时机再调一次 set_viewport（变更在帧末生效）
    --   也可以完全不动它，接受这里的引导期默认值。
    --
    --   而"在步骤 3 用用户词汇写"**做不到** —— 那时映射层还没装。
    --   作者自己的 on_game_init 在步骤 5.7，那时可以用用户词汇；
    --   两件事不是同一个时机，也不是同一个入口。
    wag.space.set_viewport(M.config.viewport)

    -- 【为什么这里要记一条】
    --   boot 在步骤 3，早于用户词汇和大多数子系统；启动后日志里应能看到
    --   它确实执行过，并且带的是最终提交的 render / strategy。
    --   这也能区分“留在默认值”与“boot 真的设过值”。
    --
    -- 【为什么带 where】把设的值一起记下来，否则日后看到这一条也不知道它设了什么。
    wag.log.info("引导期配置：视口已设定",
                 string.format("render=%dx%d strategy=%s",
                               M.config.viewport.render.w,
                               M.config.viewport.render.h,
                               tostring(M.config.viewport.strategy)))

    -- -------------------------------------------------------------------------
    --  其它启动期配置
    -- -------------------------------------------------------------------------
    --
    -- 【目前没有】boot 只负责视口；音频、输入、资源加载不在 boot 表里，
    --   它们各自在初始化/装配阶段处理。
end

return M
