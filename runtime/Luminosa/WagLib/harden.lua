-- =============================================================================
--  Luminosa/WagLib/harden.lua
--
--  环境封堵的 **Lua 第二层**。
--
--  【权威在 C++，不在这里】
--      C++ 的 `script::seal_environment()` 在读取 init.lua **之前**执行：
--        · ffi / jit 的 package.preload 封成报错函数
--        · debug 折中成只含 traceback
--      ⇒ 脚本无法跳过那一层；本文件只是幂等的第二道保险。
--
--  【本文件只负责 ffi / jit】
--      · 不重建 debug
--      · 不访问 debug.getregistry
--      · 不声称清注册表
--      这些在 C++ 已经完成；在这里重复做只会制造“看起来在清、实际没清”的死代码。
--
--  【为什么仍然保留这一层】
--      如果将来启动顺序被改动、或 harden 被独立复用，第二层仍能挡住
--      `require("ffi")` / `require("jit")`。它不依赖 C++ 的实现细节。
--
--  【为什么必须在任何用户脚本之前】
--      一旦用户脚本跑过，package.loaded / package.preload 就可能已被读过；
--      “谁已经拿到过引用”是收不回来的。
-- =============================================================================

local M = {}

-- 被封死的模块名。
local SEALED_MODULES = { "ffi", "jit" }

--- 执行第二层封堵。
--
-- 【调用点】init.lua 的步骤 1，在任何 Lumi / Nosa / Project 之前。
-- 【它不返回值】封堵本身失败应直接 error；但当前实现只做表写入，不会失败。
function M.install()
    -- -------------------------------------------------------------------------
    --  ① 把 package.preload 上的模块换成报错函数
    -- -------------------------------------------------------------------------
    --
    -- 【为什么是报错函数而不是 nil】
    --   nil 会让 require 继续走搜索路径，从而可能在文件系统上找到一个同名
    --   用户文件（例如 ffi.lua）—— 那是一条绕过路径。报错函数显式堵死它。
    for _, name in ipairs(SEALED_MODULES) do
        package.preload[name] = function()
            error(string.format(
                "模块 '%s' 已被 LuaWAG 禁用。\n" ..
                "  它被禁用的理由是：它允许脚本绕过引擎的边界，从而破坏" ..
                "'同一个项目在任何机器上走过同一段状态轨迹'这条保证。\n" ..
                "  若确实需要调用 C 库或写性能敏感的代码，请把那一部分做到" ..
                "引擎侧（C++ 侧模块），而不是从脚本直接调用。", name), 2)
        end
    end

    -- -------------------------------------------------------------------------
    --  ② 清 package.loaded（防御性）
    -- -------------------------------------------------------------------------
    --
    -- 正常启动时 C++ 已经清过；这里再清一次没有代价。
    -- 注意：Lua 5.1 里 package.loaded 就是 registry._LOADED；不需要再经
    -- debug.getregistry 拿第二份。
    for _, name in ipairs(SEALED_MODULES) do
        package.loaded[name] = nil
    end
end

return M
