-- =============================================================================
--  Luminosa/WagLib/hooks.lua
--
--  钩子槽的启动期自检。
--
--  【它不是"步骤 0 的脚本侧一半"】
--      已定的启动次序里，步骤 0（预置 13 个钩子槽）**全在 C++ 侧**，且它
--      必须发生在任何脚本之前。因此按次序，本文件**不可能**参与预置。
--
--  【它只做一件事：检查 wag.hook 上**现有的**成员是不是函数】
--
--      ❌ 它**绝不重列那 13 个名字**
--         重列会造成"同一个契约写两遍，而只有 C++ 那份是权威"。
--         而它的失效形态很坏：**两份清单悄悄分歧**，而分歧只在某个钩子
--         "永远不被调用"时暴露 —— 那时已经离原因很远了。
--
--      ✅ 它遍历表上的成员，逐个检查类型，并**报出它实际看到的成员名**
--         于是"缺了哪个"这句话由**事实**给出，而不是由一张复制的清单给出。
--
--  【它到底在防什么】
--      C++ 侧已经有三道检查，把大多数失败模式都堵了：
--        ① 步骤 0 之后立刻在 C++ 侧核对 13 个槽都是函数
--        ② 调用点：取到非函数 ⇒ 引擎内部完整性错误（**每次调用都查**）
--        ③ 白名单（名字清单）本身是 C++ 的常量数组 ⇒ 清单唯一
--
--      所以本自检挡的是剩下那一点：
--        · 步骤 0 到首次脚本执行之间**有别的代码动了 wag.hook**
--        · 或者引擎自己预置了 12 个（少一个）
--
--      ⇒ 它与 ② 的差别只在**时机**：② 在调用时发现，本文件在启动时发现。
--        本文件买到的是"启动时一次清清楚楚的失败"，而不是"某个钩子第一次
--        被调用时的一炸"。
--
--  【因此它不是必要机制】
--      它缺失时**引擎照跑**。这正是它属于"引导层的辅助件"那一类的原因。
--
--  【它跑几次】
--      一次就够。槽在步骤 0 之后不再变（除非有人刻意覆盖），而"时刻检查"
--      是调用点 ② 已经做了的事。每帧再查一遍是重复劳动。
-- =============================================================================

local M = {}

--- 检查 wag.hook 上的现有成员是否都是函数。
--
-- @return ok   全部是函数时为 true
-- @return bad  第一个不是函数的成员名（全通过时为 nil）
--
-- 【为什么返回"第一个"而不是全部】
--   一个槽不是函数通常意味着同一处的写法错了。报第一个就够了，而报全部
--   会让错误信息变长、可读性变差。
function M.verify()
    -- 【表本身必须先存在】
    --   wag.hook 由 C++ 在步骤 0 建立。若它不存在，那就不只是"某个槽不对"，
    --   而是引导层的基础设施没到位。
    if type(wag) ~= "table" then
        return false, "wag（引擎原语表）不存在"
    end
    if type(wag.hook) ~= "table" then
        return false, "wag.hook 不存在"
    end

    -- 【遍历现有成员，而不是遍历一张名字清单】
    --   这里用的是 pairs —— "这张表上有什么就查什么"。
    --   于是本文件不需要知道那 13 个名字是什么。
    local count = 0
    for name, fn in pairs(wag.hook) do
        count = count + 1
        if type(fn) ~= "function" then
            -- 【报出实际看到的成员名】这是"由事实给出答案"的落实：
            --   错误信息里的名字来自表本身，而不是来自一份手抄的清单。
            return false, string.format("%s（当前是 %s）", tostring(name), type(fn))
        end
    end

    -- 【空表也要报】
    --   一个空表说明步骤 0 完全没有生效 —— 那比"某个槽不对"更严重。
    if count == 0 then
        return false, "wag.hook 是空的（步骤 0 似乎没有生效）"
    end

    -- 【刻意没有做的事：核对个数是否恰好是 13】
    --   因为"13"这个数是**引擎侧白名单**的属性，而本文件拿到的是表上的
    --   成员。若把 13 写在这里，就又出现了一份需要维护的清单。
    --   ⇒ 个数的一致性由 C++ 侧的名字表与 static_assert 保证。
    return true, nil
end

return M
