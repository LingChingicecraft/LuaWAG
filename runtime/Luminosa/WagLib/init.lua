-- =============================================================================
--  Luminosa/WagLib/init.lua
--
--  引导入口。
--
--  【这是唯一被引擎按路径直接读取的脚本】
--      引擎知道它的路径（<安装根>/Luminosa/WagLib/init.lua），而它之下的一切
--      都由本文件按固定次序组织。
--
--  【硬约束：它不得依赖 Lumi / Nosa / Project】
--      理由：它要负责"找到并装载那三层"。若它依赖了其中任何一层，那么
--      "删掉那一层引擎仍然能起"这条就不成立了。
--      它能用的只有引擎原语（wag.*）与它自己的同目录模块。
--
--  【已定的次序】
--      步骤 0  引擎预置 13 个钩子槽   —— 已由 C++ 完成（本文件不参与）
--      步骤 1  harden   环境封堵      —— **必须在任何用户脚本之前**
--      步骤 2  hooks    自检          —— 只检查"槽是不是函数"
--      步骤 3  boot     引导期配置（视口）—— 只能用引擎原语
--      步骤 4  映射层   装配用户词汇
--      步骤 5  按层装载 ②Lumi ③Nosa ④Project
--      步骤 6  进入帧循环（由本文件**显式请求**）
--
--  【为什么步骤 6 要"显式请求"而不是"脚本返回即开始"】
--      若引擎在 init.lua 返回之后自行开始帧循环，那么"返回"与"跑完了"就是
--      同一个信号 —— 中途失败也会照进循环。显式请求让"装载没完成"与
--      "可以开始跑"在引擎看来是两个不同的状态。
-- =============================================================================

local harden = require("WagLib.harden")
local hooks_mod = require("WagLib.hooks")
local boot_mod = require("WagLib.boot")
local vocab = require("WagLib.vocab")
local load_mod = require("WagLib.load")

-- 【拖拽即暂停的默认策略（2026-11-15）】
--   ⚠️ 它**必须在这里 require**（而不是到步骤 5.6 再 require）：
--   模块在装载那一刻记下"引擎预置的 on_frame_pause 空函数"，
--   用来判断工程到底有没有自己写暂停线。晚于用户脚本 require 就抓不到了。
--   【它在 Lumi 而不是 WagLib】按分层：WagLib 是**引导层**，
--   "拖拽即暂停"是一个**策略**（增强库性质）⇒ 官方库层 `Lumi`。
local drag_pause = require("Lumi.Basic.drag_pause")

-- -----------------------------------------------------------------------------
--  记录：引导脚本已经开始跑
-- -----------------------------------------------------------------------------
--
-- 【为什么这一条放在最前面】
--   因为在本轮之前**脚本侧一条日志都没有** ⇒ "引导脚本跑完了"与"它静默地没跑"
--   在日志上长得一模一样，只能靠" C++ 有没有打出 L2/L3"反推。
--   ⇒ 这一条把"它确实开始了"钉下来，而后面每一步各记一条。
--
-- 【它们是什么性质的东西】
--   这些记录是**接线期的脚手架**：让"哪一步没跑"一眼可见。
--   等接线稳定之后，可以只留真正有价值的那几条（例如"层装载完成"）。
wag.log.info("引导脚本开始执行")

-- -----------------------------------------------------------------------------
--  步骤 1：环境封堵
-- -----------------------------------------------------------------------------
--
-- 【它必须是第一步，且必须在任何用户脚本之前】
--   一旦有脚本跑过，package.loaded["ffi"] 与注册表里的 _LOADED["ffi"] 就可能
--   已经有值，而"谁已经拿到过引用"是收不回来的。
--
-- 【它为什么在引导层，而不是在 C++ 侧做】
--   两者都可以。放在这里的原因是：封堵涉及 Lua 的 package 表与几个全局名，
--   而这些是**脚本侧的概念** —— 用 Lua 写比用 C API 写更短、更容易核对。
--   而"必须在任何脚本之前"这条由本文件的次序保证（本文件在步骤 0 之后、
--   在任何 Lumi/Nosa/Project 之前被读取）。
harden.install()

-- -----------------------------------------------------------------------------
--  步骤 2：钩子槽自检
-- -----------------------------------------------------------------------------
--
-- 【它只检查"槽是不是函数"，不重列那 13 个名字】
--   重列会造成"同一个契约写两遍，而只有 C++ 那份是权威"。那样两份清单会
--   悄悄分歧，而分歧只在某个钩子"永远不被调用"时才暴露。
--
-- 【它不是必要机制】
--   C++ 侧已有三道检查：预置后的核对、调用点的判定、名字清单唯一。
--   它买到的只是"启动时一次清清楚楚的失败"，而不是"某个钩子第一次被调用
--   时的一炸"。⇒ 它缺失时引擎照跑（它是引导层的辅助件，不是引擎必需件）。
local ok, bad = hooks_mod.verify()

if not ok then
    -- 【失败时的处理】
    --   走**引擎侧的报错入口**，级别 L3（引导层完整性被破坏 ⇒ 不能带错继续）。
    --   而提示要**指向 C++ 的预置**，而不是让它看起来像"用户写错了"。
    --
    -- 【为什么用 wag.fail 而不是 Lua 的 error()】
    --   原先这里写的是 `error(...)`，而它有两个问题：
    --     ① 它走 `pcall` 边界 ⇒ 实际级别是 **L2**，与"应当是 L3"不符
    --        （注释里一直写着 L3，而代码是 L2 —— 典型的"注释与代码不一致"）
    --     ② 它是**脚本自己的**报错，引擎无法与"引擎侧的故障"区分
    --   ⇒ `wag.fail` 现在可用了：`level = wag.log.level.terminate` 让它终止。
    wag.fail{
        level = wag.log.level.terminate,
        where = "wag.hook 的槽",
        got = tostring(bad),
        want = "13 个槽都是函数（请检查引擎的步骤 0 预置）",
        sentence = "[引擎内部] 引导层完整性被破坏：wag.hook 上有槽不是函数",
    }
end

wag.log.info("钩子槽自检通过")

-- -----------------------------------------------------------------------------
--  步骤 3：引导期启动配置（视口）
-- -----------------------------------------------------------------------------
--
-- 【2026-11-18 改定】这一步**不再叫 on_game_init**，也**不再是它的钩体**。
--   原因：项目层要到步骤 5 才装载，若 init 在这里跑，作者写的 `GameInit`
--   就是死代码。⇒ 把两件事分开：
--     · 这一步 = "引导期配置"（视口），只能用引擎原语（映射层还没装）
--     · `on_game_init` = 作者的初始化，移到**步骤 5.7**（层装载完成后）
--
-- 【为什么视口必须在这里设】映射层要读它设定的配置 ⇒ 它必须在映射层之前。
boot_mod.run()
wag.log.info("步骤 3 完成：引导期配置已应用（视口）")

-- -----------------------------------------------------------------------------
--  步骤 4：装配用户词汇
-- -----------------------------------------------------------------------------
--
-- 【映射层住在 WagLib 里，而它是"必须随引擎版本发布"的那一类】
--   理由：映射表把"用户词汇"对应到"引擎槽与引擎原语"，而引擎侧的槽名与
--   原语名**会随引擎版本变**。若它住在内容侧，就会出现"映射表版本"与
--   "引擎版本"两个版本，而错位就是一堆看不懂的报错。
--
-- 【它与"引擎必需"那一类的区别】
--   删掉它，引擎照跑（只是所有用用户词汇写的脚本会炸）。
--   因此它是一条**特赦**：它命中"必须随引擎版本发布"这条判据，而不是
--   "删了引擎起不来"那条。
vocab.install()
wag.log.info("步骤 4 完成：用户词汇已装配")

-- -----------------------------------------------------------------------------
--  步骤 4.5：装配官方库命名空间（lumi.*）
-- -----------------------------------------------------------------------------
--
-- 【为什么它在用户层之前】
--   因为 Lumi / Nosa / Project 都会用到 `lumi.screen` —— 若它装得晚，
--   那些层里对它的引用全是 nil。
--
-- 【它为什么在 WagLib 里，而不是在 Lumi 那一层】
--   因为它把"脚本词汇"接到"引擎原语"上（`lumi.screen` → `wag.space.set_window_size`），
--   而那个原语名**会随引擎版本变** ⇒ 命中"必须随引擎版本发布"那条判据
--   （与 vocab.lua 同类，见其文件头）。
--
-- 【它不读配置、不做选择】
--   装完只提供入口。选哪一项由 boot 层或项目决定 ——
--   "启动时窗口多大"是一次**决策**，不该藏在装载动作里。
--
-- 【lumi 这张表由这里建】
--   内核只建 `wag`（步骤 0），不建 `lumi` / `nosa` —— 那两层的命名空间属于
--   脚本侧的组织，而"层"这个概念本身就是引导层的编排。
--   若在这里直接写 `lumi.screen = ...` 而 lumi 不存在，会索引 nil 报错。
lumi = lumi or {}

local screen_mod = require("WagLib.screen_select")
lumi.screen = screen_mod
wag.log.info("步骤 4.5 完成：lumi.screen 已装配")

-- -----------------------------------------------------------------------------
--  步骤 4.6：装配 wag.text（库层文字入口，2026-11-16 / P7 阶段1）
-- -----------------------------------------------------------------------------
--
-- 【为什么装在 wag.* 而不是 lumi.*】《文字与富文本排版决策》§4.6 定的名字就是
--   `wag.text.label` / `wag.text.rich`。而"引擎侧没有字体对象"（§14.2 D2）⇒
--   这张表是**库层装上去的**，引擎不认识它。
local text_mod = require("Lumi.Basic.text")
wag.text = text_mod
wag.log.info("步骤 4.6 完成：wag.text 已装配")

-- -----------------------------------------------------------------------------
--  步骤 5：按层装载
-- -----------------------------------------------------------------------------
--
-- 【次序固定为 ②Lumi ③Nosa ④Project】
--   每一层可以使用它下面的各层以及它自己。模块名带层前缀，
--   不同层不会因同名互相覆盖；需要替换请显式 require/替换文件。
load_mod.load_layers()
wag.log.info("步骤 5 完成：层装载结束")

-- -----------------------------------------------------------------------------
--  步骤 5.6：安装"拖拽即暂停"默认策略（2026-11-15）
-- -----------------------------------------------------------------------------
--
-- 【为什么在层装载之后】它要包装工程自己的 `on_frame_main` —— 早于工程装载就没有
--   可包装的钩体了。
--
-- 【它会不会锁死】不会：模块自己带安全阀 —— 若工程的 `on_frame_pause` 还是
--   引擎步骤 0 预置的空函数（= 没有暂停线），它**跳过安装**并记一条 L1。
--   否则"拖一下窗口，游戏再也回不来"。
drag_pause.install()

-- -----------------------------------------------------------------------------
--  步骤 5.7：on_game_init（层装载完成后的一次，2026-11-18 新增）
-- -----------------------------------------------------------------------------
--
-- 【它为什么在这里而不是步骤 3】项目层到步骤 5 才装载 ⇒ 若在步骤 3 调，
--   作者写的 `GameInit` 还不存在，那个槽永远是空函数（= 死代码）。
--
-- 【它为什么由引导层调、而不是引擎调】引擎不认识"层装载完成"这个时刻；
--   而"脚本调脚本"不违法公理 14（那条管的是**引擎→脚本**的回调）。
--
-- 【实参是空表】此时没有"本帧"（内核规范 §9.2）。
--
-- 【出错 ⇒ 终止】init 的语义是"配好了才能跑"；带错继续会让后面所有阶段
--   建立在半初始化的状态上。级别是终止级（与"引导层完整性被破坏"同档）。
local ok_init, err_init = pcall(wag.hook.on_game_init, {})
if not ok_init then
    wag.fail{
        level = wag.log.level.terminate,
        where = "on_game_init",
        got = tostring(err_init),
        want = "一次不抛错的初始化",
        sentence = "on_game_init 执行出错（初始化未完成，不能进入帧循环）",
    }
end
wag.log.info("步骤 5.7 完成：on_game_init 已执行（层装载之后）")

-- -----------------------------------------------------------------------------
--  步骤 6：请求进入帧循环
-- -----------------------------------------------------------------------------
--
-- 【已决：这个入口**只置一个标志**，不驱动循环】
--   循环仍然归 main。脚本侧只表达"我装载完了、可以开始跑"这个意图。
--
--   【为什么不是"同步驱动循环"（那个方案被否掉了）】
--     若它同步跑循环，那么"引擎的主循环"与"一个脚本可调用的函数"就成了同一个
--     东西，而 main 不再是唯一拥有循环的地方。
--     而只置标志还有一个好处：**若 init.lua 在上面任何一步失败，
--     标志就不会置上** ⇒ main 能分辨"装载完成"与"装载中途失败"，
--     而不是像"返回即开始"那样把两者当成同一个信号。
--
-- 【它不属于 wag.engine】
--   wag.engine 的四个成员负责"引擎**是否在运行**"，而"开始运行"是启动流程的
--   一部分。加进去会破坏那四个成员的完整性证成（"一个事件不能是自己的前提"）。
wag.log.info("步骤 6：请求进入帧循环")
wag.boot.run()
