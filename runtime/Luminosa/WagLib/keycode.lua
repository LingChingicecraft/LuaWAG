--  KEY / MOUSE：名字 → SDL scancode / 鼠标按钮编号。
--
--  【为什么是"名字 → 数字"，而不是引擎认识名字】
--    引擎只收 scancode（0..511）与按钮（1..5）；名字表在脚本侧，
--    改键只改这一层（见《输入子系统设计》I9 / I14）。
--
--  【数值来源】SDL3 的 SDL_scancode.h —— **不要手抄**；本表由它生成。
--    物理位置语义：KEY.A 指 QWERTY 的 A 键位，与键盘布局/字符无关。
--
--  【长度】SDL 只给有名字的 scancode；未列出的值依然是合法 scancode
--    （引擎不禁止），只是没有名字可用。
--
--  【别名】ENTER/RETURN、ESC/ESCAPE、SHIFT/LSHIFT 等给常用别名，
--    值相同；改键 UI 用 NAME 反查（同名多值时取**第一个**）。
--
--  【MOUSE】LEFT=1 / MIDDLE=2 / RIGHT=3 / X1=4 / X2=5（与 SDL 一致）。
-- =============================================================================

