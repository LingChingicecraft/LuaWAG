-- =============================================================================
--  Luminosa/WagLib/load.lua
--
--  按层装载：②Lumi ③Nosa ④Project。
--
--  【它与 resolve.lua 的分工 —— 这是已定的】
--      resolve：**找得到吗**（纯路径解析，无副作用，易单测）
--      load   ：**按什么次序装**（会执行代码，有副作用，会失败）
--      两者的性质不同，因此不合并 —— 混在一起会让错误归因变难：
--      一个"目录找不到"与一个"模块里报错"会被报成同一类失败。
--
--  【已定的装载次序】
--      ① → ② → ③ → ④。
--      模块名带层前缀（Lumi.Basic.rng / Project.main），不同层不会因同名互相覆盖；
--      “后面的层覆盖前面的层”不是本装载器的规则，需要覆盖请显式 require。
--
--  【当前实现状态 · 2026-11-19】
--      resolve.list_modules() 已接 wag.fs.list_files，按层目录扫描 .lua。
--      init.lua 不再手动 require Lumi.Basic.rng / shader / atlas / Project.main。
-- =============================================================================

local M = {}

local resolve = require("WagLib.resolve")

--- 按 ②③④ 的次序装载所有层。
--
-- 【调用点】init.lua 的步骤 5，在映射层装配之后。
--
-- 【为什么在映射层之后】
--   因为 Lumi / Nosa / Project 里的代码会**使用用户词汇**（它们就是按那些
--   名字写的）。若装载在映射层之前，它们的每一个调用点都会是 nil。
--
-- 【它不返回值】单个模块的装载失败不应当让整局失败 —— 那属于"可降级的
--   资源失败"那一类（记 L2 后继续）。而"某一层整个不存在"更轻（记 L1）。
function M.load_layers()
    for _, layer in ipairs(resolve.layers) do
        M.load_one_layer(layer)
    end
end

--- 装载一个层。
--
-- @param layer  resolve.layers 里的一项
--
-- 【已定：缺失某一层 ⇒ 引擎仍要能起，记 L1 并继续】
--   因此"目录不存在 ⇒ 模块列表为空 ⇒ 什么都不装"是正常路径，不是错误。
function M.load_one_layer(layer)
    local modules = resolve.list_modules(layer)

    if #modules == 0 then
        -- 【它不是错误】缺失某一层是合法的（例如一个项目只用官方库，
        --   没有额外第三方库）。记 L1 即可。
        --
        -- 【为什么"什么都不做"不够】因为那样"这一层不存在"与"这一层存在、
        --   但一个模块都没装成"在日志上完全一样 ⇒ 排查时无从下手。
        wag.log.info(string.format("层目录不存在或为空，跳过：%s", layer.name))
        return
    end

    for _, module_name in ipairs(modules) do
        M.load_one_module(layer, module_name)
    end
end

--- 装载一个模块。
--
-- @param layer       所属层（用于报错定位）
-- @param module_name 模块名
--
-- 【单模块失败的粒度】
--   一个模块装载失败 ⇒ **记下来并继续装下一个**，而不是整局失败。
--   理由：那是"可降级的资源失败"（记 L2 后继续）。
--   而若那个模块是整个游戏的主逻辑，它的失败会在别处以别的方式显形 ——
--   那时错误信息里已经有它装载失败的记录。
--
-- 【为什么用 pcall】
--   因为这里要"继续装下一个"，而 require 的错误是抛出的。
--   注意这与"引擎内部的跨边界校验不兜底"**不冲突**：
--      · 跨边界校验面对的是"数据矛盾"，它的处理是终止 —— 不兜底是对的
--      · 而这里面对的是"某个模块写错了"，它的处理是"这一个不装，继续" ——
--        这本身就是已定的行为（L2）
--   ⇒ 也就是说：pcall 在这里不是"兜底"，而是"实现那条已定的可降级行为"。
function M.load_one_module(layer, module_name)
    local ok, err = pcall(require, module_name)

    if not ok then
        -- 【L2：记一条，然后继续装下一个】
        --
        -- 【错误信息里必须带什么】哪个层、哪个模块。少了这两个，"某个模块
        --   装载失败"就变成了一条无法定位的记录。
        --
        -- 【为什么把 require 的原错误也带上】
        --   因为"模块里报错了"与"模块找不到"是两种完全不同的失败，
        --   而它们的处置完全不同（前者是作者写错了，后者可能是路径/命名问题）。
        --   只记"装载失败"就会把两者压成一句话 —— 这正是本轮在引导脚本上
        --   踩过的坑（"读不到"掩盖了"里面 require 失败"）。
        wag.log.warn(string.format("模块装载失败：%s", module_name),
                     string.format("层=%s 原因=%s", layer.name, tostring(err)))

        -- 【为什么不在这里重试】因为重试不会改变结果（模块是确定性的），
        --   而它会掩盖真正的失败。
    end
end

-- -----------------------------------------------------------------------------
--  关于"进入帧循环"的入口 —— **它不在这里**
-- -----------------------------------------------------------------------------
--
-- 【入口是哪一个】
--   `wag.boot.run()`（C++ 侧注册，见 `script/primitives.cpp` 的 `l_boot_run`）。
--   已决（乙方案）：它**只置一个标志就跑完返回**，不驱动循环 ——
--   循环仍归 `main`。`init.lua` 的步骤 6 直接调它。
--
-- 【它为什么不属于 wag.engine】
--   `wag.engine` 的四个成员管"引擎**是否在运行**"，而"开始运行"是启动流程的
--   一部分。加进去会破坏那四个成员的完整性证成（"一个事件不能是自己的前提"）。
--
-- 【不要再在脚本侧加第二层包装】
--   那会让“进入帧循环”有两个入口，而只有一个是真的。
--   ⚠️ **不要**再在脚本侧加第二层包装：那会让"进入帧循环"有两个入口，
--      而只有一个是真的。
--
return M

