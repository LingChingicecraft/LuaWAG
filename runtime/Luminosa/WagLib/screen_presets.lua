-- =============================================================================
--  Luminosa/WagLib/screen_presets.lua
--
--  分辨率清单：**数据**，不是行为。
--
--  【它是什么】
--      一张"名字 → { w, h }"的表，配上加载时的自检。
--      它是**引擎/官方发的清单**，不是给玩家看的选项列表 ——
--      玩家看到什么名字、暴露哪几项，是**游戏侧**自己的表（二次映射）决定的。
--
--  【为什么它在 WagLib 里】
--      和 vocab.lua 同类：它把"脚本侧的词汇"接到"引擎侧的量"上，而引擎侧的
--      约定（窗口尺寸的单位、set_window_size 的签名）**会随引擎版本变**。
--      若它住在内容侧，就会出现"清单版本"与"引擎版本"两个版本 —— 而它们的
--      对应关系没人管。
--
--  【单位是**窗口尺寸**，不是 DIP】
--  当前平台窗口尺寸与客户区物理像素同值；不要把它当 DIP。
--      理由：引擎那条"凡是与画面尺寸有关的路，都不经过 dpi"必须连到脚本侧。
--      若这里存 DIP，那么从表到引擎之间就要乘一次显示比例，于是又多一个
--      "乘错就偏 1.5 倍"的位置 —— 而我们刚为那个形状付过几次学费。
--      ⇒ 要按显示器缩放适配的，那是**策略**，住在游戏侧的二次映射里。
--
--  【为什么只有 w 与 h，没有"比例"字段 —— 这一条是踩过坑之后定的】
--
--        ① **它没有任何消费者**：引擎不读它（引擎只收两个数），库也不用它
--           分组筛选。它是"为了将来"而存在的字段，而那个将来还没到。
--        ② **它要求作者做一道非本意的算术**：显示器行业对 2560×1080 的俗称是
--           "21:9"，而它的**真实化简比例是 64:27**；1920×1200 俗称"16:10"，
--           真实化简比例是 8:5。也就是说"俗称"与"化简比例"经常不一致，
--           而要求字段化简就等于要求作者去算那个他本来没打算算的数。
--           （这个坑让我连写错两次 —— 规则不好用，本身就是证据。）
--        ③ **它买不到当前需要的东西**：宽高是否一致，由 `w` 与 `h` 自己就定了；
--           而"比例写错"这件事在使用时一眼就能看出来（窗口比例不对），
--           不需要在加载期强求一个冗余字段。
--
--      ⇒ 于是自检退化为"w 与 h 是正整数"。它仍然能抓住真错
--        （打成 0、打成小数、写成字符串、写成负数）。
--
--  【与 set_viewport 的 render 矩形是什么关系 —— 没有任何关系】
--      本清单只管**窗口多大**。而"世界的可见范围渲染成什么"归
--      `wag.space.set_viewport` 的 render 管。
--      两者的**宽高比不必相同** —— 那正是信箱存在的意义。
--      千万不要让本模块去写 render（那会让同一个字段有两个写入者）。
-- =============================================================================

local M = {}

-- -----------------------------------------------------------------------------
--  清单
-- -----------------------------------------------------------------------------
--
-- 【格式（这是契约，作者必须遵守）】
--      名字（键）   任意字符串。它是**长期引用**用的标识，
--                   所以游戏侧的表与存档用**名字**而不是下标。
--      w, h         正整数，物理像素。要申请给引擎的尺寸。
--
-- 【作者可以直接改这张表】
--      · 若只想增减几项 ⇒ 改这里
--      · 若整张表都要换 ⇒ 在 Project 层定义同名的表把它覆盖掉
--        （模块名带层前缀；需要替换请显式 require/替换文件，不依赖注册机制）
--
-- 【里面的项只是"常见值"】
--      这不代表引擎限制了什么：`set_window_size` 接受任意 > 0 的尺寸，
--      "清单里有哪些"纯粹是这一张表的内容。
M.list = {
    -- 16:9
    ["720p"]  = { w = 1280, h = 720 },
    ["1080p"] = { w = 1920, h = 1080 },
    ["1440p"] = { w = 2560, h = 1440 },

    -- 8:5（1920×1200）
    ["1200p"] = { w = 1920, h = 1200 },

    -- 4:3
    ["xga"]   = { w = 1024, h = 768 },
    ["uxga"]  = { w = 1600, h = 1200 },

    -- 超宽（2560×1080；俗称"21:9"，真实化简比例是 64:27 —— 而这不重要，
    --   因为清单里只存两个数）
    ["uwfhd"] = { w = 2560, h = 1080 },

    -- 1:1（正方形，用于"窗口化小窗"这类用途）
    ["square"] = { w = 1080, h = 1080 },
}

-- -----------------------------------------------------------------------------
--  自检
-- -----------------------------------------------------------------------------
--
-- 【为什么在**加载时**做，而不是用时】
--      用时才发现，等于把错误推迟到"最不适合定位它的时刻"（游戏跑起来之后，
--      而错误信息离原因很远）。
--      这与已定的"跨边界处校验"是同一条：这里是脚本侧的内部一致性校验。
--
-- 【单条无效怎么办 —— 剔除该条并记 L2，而不是整表失败】
--      理由：这是**可降级**的失败（少一个预设，游戏照跑）。
--      而"整表为空 ⇒ 没有任何可用项"更严重，那由调用点处理。
--
-- 【日志入口】`wag.log.warn` 已存在，加载时把坏项逐条报出去。

--- 校验一条。
--  @return true, nil 或 false, 原因（字符串）
local function check_one(e)
    if type(e) ~= "table" then
        return false, "不是表"
    end

    local w, h = e.w, e.h

    if type(w) ~= "number" or type(h) ~= "number" then
        return false, "w 或 h 不是数"
    end
    if w <= 0 or h <= 0 then
        return false, "w 或 h 不是正数"
    end
    if w ~= math.floor(w) or h ~= math.floor(h) then
        -- 【为什么要求整数】窗口尺寸最终要收成整数像素（平台接口收 int）。
        --   允许小数就等于允许"一个会被静默取整的值"，而静默取整是难查的。
        return false, "w 或 h 不是整数"
    end

    return true, nil
end

--- 校验整张清单，并**剔除**无效项。
--
-- @return ok(布尔), bad(表：{ {名字, 原因}, ... })
--
-- 【为什么必须剔除，而不只是报告】
--   只报告的话，无效项会**留在 list 里**：
--       · `names()` 照样返回它们
--       · `choose()` 会把它们推给引擎
--   ⇒ 那就成了"自检发现了，但没人拦"。已定的行为是"单条无效 ⇒ 跳过该条"。
--
-- 【⚠ 剔除带来的一个坑：结果**不可重复观察**】
--   本函数在加载时被调用一次；那一次之后，被剔除的项就不在 list 里了。
--   于是**第二次调用看到的"坏项"通常是空的** —— 那不代表清单干净。
--   ⇒ 所以调用方**必须在第一次调用时**就把 bad 处理掉（记日志/报给作者），
--     模块把它留在 `M.load_bad` 上（见文件末尾），并在加载时直接 wag.log.warn。
function M.verify()
    local bad = {}
    for name, entry in pairs(M.list) do
        local why = nil
        if type(name) ~= "string" then
            why = "名字（键）不是字符串"
        else
            local ok, reason = check_one(entry)
            if not ok then
                why = reason
            end
        end

        if why ~= nil then
            bad[#bad + 1] = { tostring(name), why }
            -- 剔除（键不是字符串时也一样：那种项不可能被按名引用）
            M.list[name] = nil
        end
    end
    return #bad == 0, bad
end

--- 取一条。
--  @return  命中时返回 { w, h }（同一张表，只读用）；否则 nil
function M.get(name)
    if type(name) ~= "string" then
        return nil
    end
    return M.list[name]
end

--- 全部名字，**已排序**。
--
-- 【为什么排序】因为 `pairs` 的次序不确定，而"选项列表"给玩家看时必须是稳定的
--   —— 否则每次启动菜单里的顺序都不同。
function M.names()
    local out = {}
    for name in pairs(M.list) do
        out[#out + 1] = name
    end
    table.sort(out)
    return out
end

-- -----------------------------------------------------------------------------
--  加载时自检一次，并**立刻把坏项报出去**
-- -----------------------------------------------------------------------------
--
-- 【失败时不终止】单条无效 == 可降级 ⇒ 剔除掉，继续。
--
-- 【为什么必须在这里就报，而不是留给调用方】
--   因为剔除之后**结果不可重复观察**：本函数跑过一次之后，被剔除的项就不在
--   list 里了 ⇒ 再调 M.verify() 看到的"坏项"永远是空的（见 M.verify 的说明）。
--   ⇒ 所以"报出去"这个动作只能在**这一次**做。
--   ⇒ `M.load_bad` 仍然保留，供工具/repl 检查；实际报告由下面的 wag.log.warn 完成。
--
-- 【它依赖一个次序，值得点名】
--   本模块是在**被 require 时**跑这一段，而 require 链条是：
--       init.lua → screen_select → screen_presets（到这里）
--   此时 `wag.log` **必须已经存在** —— 它由引擎在"注册引擎原语"那一步建立,
--   而那一步在读引导脚本**之前**。
--   ⇒ 若将来有人把原语注册挪到读脚本之后，这里就会在 nil 上索引而报错。
M.load_ok, M.load_bad = M.verify()

for _, item in ipairs(M.load_bad) do
    wag.log.warn(string.format("分辨率清单里有一项无效，已剔除：%s", item[1]),
                 string.format("原因=%s", item[2]))
end

return M
