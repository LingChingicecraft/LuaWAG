// =============================================================================
//  wag/error/error.hpp
//
//  内核：错误架构。
//
//  【一句话总纲】
//      **一个决策点 + 两个入口。** 不是两套报错路径。
//
//  【为什么必须只有一个决策点】
//      若 C++ 与 Lua 各有各的报错路径，两条路径会**各自演化**，迟早出现
//      "同一种错在两处行为不同"。而那种分歧只在罕见的错误路径上暴露 ——
//      是最难查的一类缺陷。
//
//  【入口数量由"谁有语句"决定】
//      · C++ 有语句 ⇒ 它可以直接调用一个报错函数（本文件）
//      · Lua 只能用 error()（只够 L1/L2，且只能带一个值）
//        ⇒ 它另需一个"抛带上下文错误值"的入口（在 script/bind 一侧注册）
//        ⇒ 而那个入口**不需要自己打印或弹窗** —— 它只构造错误值并抛出，
//          最终由 C++ 的 lua_pcall 接住，于是单一路径得以保住
//
//  【三条正交轴】
//      ① 类别：这是什么性质的错
//      ② 严重级别：该怎么反应
//      ③ 上下文：定位所需
//      只有 ② 决定行为，① 决定"谁来报"，③ 决定"报什么"。
//      而"错误来自哪一侧"**不进入这三条轴**。
// =============================================================================

#pragma once

#include "log/log.hpp"

#include <cstdint>
#include <string>
#include <string_view>

// 【命名空间】原 `wag::core`，现为 `wag::`（变更记录见 log/log.hpp 文件头）。
namespace wag {

// -----------------------------------------------------------------------------
//  error_class —— 错误的类别
//
//  【它与严重级别的关系是"多对一"】
//      六个类别映射到三个级别。映射表见 class_severity()。
// -----------------------------------------------------------------------------
enum class error_class : std::uint8_t {
    /// a 边界校验：脚本传进来的东西不合法（例如 NaN、无穷、零尺寸）。
    ///
    /// 【它的行为】L3。报错（带上下文）；**该调用整体不生效**；后续调用照常。
    boundary_validation,

    /// b 内部不变量：引擎自己算出的东西不成立。
    ///
    /// 【它与边界校验的区别】边界校验是"输入的错"，内部不变量是"引擎的错"。
    ///   后者意味着引擎有 bug，因此走 C++ 侧路径，**不得"带错继续"**。
    internal_invariant,

    /// c 资源失败：加载失败、内存不足、设备丢失。
    ///
    /// 【它为什么单独成一类】因为它的级别**视情形而定**：可降级的记 L2 后
    ///   继续，不可降级的 L3。而且——**每一种资源都要各自写明**，不能靠
    ///   "几乎不可能"。OOM 不是"几乎不可能"，它是真的会发生。
    resource_failure,

    /// d 关闭序列里出错。
    ///
    /// 【它的级别是固定的 L1】因为那时已经无法回到脚本继续运行。
    ///   因此不弹窗、不"带错继续"，只记日志然后继续关闭。
    shutdown_error,

    /// e 脚本自身的错：用户的 bug。
    ///
    /// 【它的行为】L2。弹窗后继续。
    script_error,

    /// f 引擎接口误用：违反接口约束（例如策略名写错）。
    ///
    /// 【它与脚本错误的区别】只是来源上的区别 —— 它仍然是"调用方写错了"，
    ///   所以行为与 e 相同。分开成两类是为了让日志里的分类更准确，而不是
    ///   为了让行为不同。
    api_misuse,
};

/// 类别 → 严重级别的映射。
///
/// 【注意类型名是 log::severity】
///   严重级别随日志那一组一起住在 `wag::log` 里（见 log/log.hpp 文件头的
///   命名空间变更记录）。因此本文件的返回类型写作 log::severity。
///
/// 【这是那张决策表在代码上的落点】改动它等于改动整个引擎的报错行为，
///   因此它必须是**唯一**的一处映射。
///
/// 【E5：六类 → 四档】判据不是"谁报的"，而是**世界有没有被污染**（E3）：
///   · 调用者给的数据不合法、且报错在副作用之前 ⇒ **L3（raise）**：事务未生效，可交还
///   · 引擎自证不成立、或副作用已发生          ⇒ **L4（terminate）**：世界不可信
///
/// 【注意 resource_failure】它返回 **L3**（不是 L4）作为默认：资源失败时
///   **结构没坏**，只是这一次失败了 ⇒ 可交还。可降级的资源由调用点显式改用
///   `log::warn()` —— 那个判断需要资源的知识，留在调用点是对的。
[[nodiscard]] constexpr log::severity class_severity(error_class c) noexcept {
    switch (c) {
    case error_class::boundary_validation:
        // 调用者数据非法；调用约束要求"在副作用之前报" ⇒ 事务未生效 ⇒ 可交还
        return log::severity::raise;
    case error_class::internal_invariant:
        // 引擎自己算出的东西不成立 ⇒ 世界不可信 ⇒ 没有退路
        return log::severity::terminate;
    case error_class::resource_failure:
        // 默认"不可降级"，但结构未损 ⇒ 仍是可交还的 L3
        return log::severity::raise;
    case error_class::shutdown_error:
        return log::severity::record;
    case error_class::script_error:
        return log::severity::warn;
    case error_class::api_misuse:
        return log::severity::warn;
    }
    // 枚举里出现了未处理的值。这本身是内部不变量被破坏。
    return log::severity::terminate;
}

/// 类别的可读名字（用于诊断输出）。
[[nodiscard]] const char* class_name(error_class c) noexcept;

// -----------------------------------------------------------------------------
//  一个结构化的错误值
//
//  【为什么要"结构化"而不是一个字符串】
//      因为跨边界校验需要**精确定位**："第 3 个顶点的 x 是 NaN"这句话里的
//      "第 3 个"必须是一个字段，而不是拼进句子里的文字。有了字段：
//        · 日志可以机读
//        · 测试可以断言具体是哪一项出错
//        · 两个渲染器（弹窗 / 日志）消费同一份数据，不可能分歧
//
//  【为什么同时允许"字符串快捷方式"】
//      对简单错误（例如"配置里缺字段"）写四个字段是啰嗦的。允许调用点只给
//      一句话，而本结构体在内部把它包成同一个形状 ⇒ **下游只认一种形状**。
// -----------------------------------------------------------------------------
struct error_value {
    /// 错误的类别。
    error_class cls = error_class::internal_invariant;

    /// 出问题的位置：哪个参数、或哪个元素的第几项。
    /// 例："第 3 个顶点的 x"。
    std::string_view where;

    /// 实际拿到的值。例："nan"。
    std::string_view got;

    /// 期望的值或范围。例："有限实数"。
    std::string_view want;

    /// 当调用点只有一句话时的整句文本。
    /// 若 where/got/want 为空，则规范文本就是它。
    std::string_view sentence;
};

// -----------------------------------------------------------------------------
//  三个入口（C++ 侧）
//
//  【它们各自对应一个严重级别，而级别由类别推出来】
//      调用方给类别，本模块查表得到级别，然后交给 log 的决策点。
//      ⇒ 调用方**不直接给级别** —— 级别是类别的函数，不是调用点的自由选择。
//        这一点保证了"同一种类别的错在引擎任何位置行为一致"。
// -----------------------------------------------------------------------------

/// 报一条跨边界校验失败（L3）。
///
/// 【调用约束】**只在副作用发生之前调用。**
///   已定："引擎先校验全部参数，确认无误之后才动手。" 因此报错时那一次调用
///   没有产生任何副作用 ⇒ 不需要回滚。
///
/// 【E8：它有两条出路，由"有没有可交还的调用者"决定】
///   · **有**（在某个 `lua_pcall` 之内）⇒ **抛**：把错误交回脚本，`pcall` 接得住。
///   · **没有**（启动 / 关闭 / main 等宿主路径）⇒ **终止**（L4）。
///   判据不是"谁调用的"，而是**有没有落点** —— `lua_error` 是 longjmp，
///   没有 `lua_pcall` 在下面接，它无处可去。
///
/// 【它仍然标记 noreturn】两条出路都不返回。
[[noreturn]] void fail_boundary(const error_value& e);

// -----------------------------------------------------------------------------
//  交还通道（E8 的实现基础）
//
//  【为什么"有没有落点"要计数，而不是一个布尔】
//    引擎→脚本的调用可以嵌套：钩子里再调原语、原语里再抛。
//    只有**最内层**那次 `lua_pcall` 是落点；计数让判断成为 O(1)，
//    不必去问 Lua（它没有这个查询）。
//
//  【谁来加/减】**只有 script 层**，围绕每一次 `lua_pcall`。
//    这是"谁建立落点，谁负责记账"。
// -----------------------------------------------------------------------------

/// 进入一次"可交还的边界"（围绕一次 `lua_pcall`）。
void enter_hand_back() noexcept;

/// 离开那次边界。
void leave_hand_back() noexcept;

/// RAII 版本。**推荐用这个** —— 它保证配对。
struct hand_back_scope {
    hand_back_scope() noexcept { enter_hand_back(); }
    hand_back_scope(const hand_back_scope&) = delete;
    hand_back_scope& operator=(const hand_back_scope&) = delete;
    ~hand_back_scope() noexcept { leave_hand_back(); }
};

/// 交还通道：由 script 层安装（只有它持有 `lua_State`）。
///
/// 【契约（实现方必须遵守）】
///   · 有落点 ⇒ **抛（longjmp，永不返回）**；
///   · 没有落点 ⇒ **正常返回**，让 `fail_boundary` 去终止。
///   这样"能不能交还"只在一处判断（实现方看计数），error 不必知道 Lua 的存在。
///
/// 【为什么参数是 message 而不是 error_value】
///   L3 抛的是**字符串**（E7）。结构化字段在 error 侧已经拼进那句话里了；
///   抛出去的一方只需要一个已经成形的文本。
using boundary_raiser = void (*)(std::string_view message);

/// 安装 / 卸载（传 nullptr）交还通道。进程生命周期内只会有一个实现。
void set_boundary_raiser(boundary_raiser r) noexcept;

// -----------------------------------------------------------------------------
//  pending raise（E11 的 ③b）
//
//  【为什么需要"暂存"】E11 的规则是「L3 **未捕获**才写 errors.jsonl」，
//    所以记录点在**捕获处**；而脚本的 `file:line` 只有抛错那一刻才知道。
//    ⇒ 抛之前把内容存下来，抛的途中由 script 层补位置，捕获点落盘。
//
//  【为什么存的是拷贝而不是 views】`error_value` 的字段是 `string_view`，
//    指向调用者的临时缓冲；`longjmp` 之后那些缓冲已经不在了 ⇒ 必须复制。
// -----------------------------------------------------------------------------

/// 抛错之前暂存一条待落盘的记录（`fail_boundary` 内部调用）。
void stash_raise(const error_value& e) noexcept;

/// 由 script 层在抛出去之前补上脚本位置（`file` 可为 nullptr）。
void set_raise_position(const char* file, int line) noexcept;

/// 在**捕获处**落盘并清空。没有被捕获的 raise 不写（这就是 E11 的规则）。
///
/// 【为什么捕获处调它而不是"每条 pcall 都调"】只有 pcall 失败才是"未捕获"。
///   成功返回的 pcall 里若发生过一次被脚本 `pcall` 接住的 raise，
///   pending 早已被**内层**的捕获点清掉了 —— 所以这里不会误报。
void flush_pending_raise() noexcept;

/// 报一条**无可交还**的边界错误（E8 的第二个入口）：**无条件 L4**。
///
/// 【什么时候用】有交还者，但**交还本身没有意义**：
///   · 脚本显式声明"这是致命的"（`wag.fail{level = wag.log.level.terminate}`）；
///   · 宿主路径（启动 / 关闭 / main），那里根本没有 `lua_pcall`。
///
/// 【它与 fail_boundary 的唯一区别】后者会看"有没有落点"；本函数不看 ——
///   调用方已经知道"这次不该活下去"。
[[noreturn]] void fail_host(const error_value& e);

/// 报一条**内部不变量被破坏**。
///
/// 【调用约束】它意味着引擎有 bug。走 C++ 侧路径，**不得"带错继续"**。
[[noreturn]] void fail_internal(std::string_view what);

/// 报一条脚本自身的错误。
///
/// 【它不终止】按 L2 处理：弹窗后继续。
/// 【"继续"的精确含义】不是"继续执行那个出错的调用"（那个调用的行为未定义），
///   而是**继续推进帧结构** —— 后面的阶段照常走完。这一点很重要，因为阶段
///   之间的有序关系必须保住（阶段 10 必须在阶段 11 之前）。
void fail_script(std::string_view what);

/// 报一条**接口误用**。
///
/// 【它与 fail_script 的区别】只是类别不同（`api_misuse` vs `script_error`），
///   行为相同（都是 L2）。分开的理由是让日志里的分类准确 —— 这一条在
///   error_class 的注释里已经写明。
///
/// 【它为什么必须存在 —— 这一条修的是一个真实的形状错误】
///   在它出现之前，界面上"策略名写错"这类错误走的是 `fail_boundary` ⇒ 级别 L3
///   ⇒ **引擎被终止**。而"调用方传了一个不认识的名字"是"调用方写错了"，
///   应当记一条 L2 然后继续（那一次调用当作没发生）。
///
/// 【参数为什么是 error_value 而不是一个字符串】
///   因为它要的是结构化上下文（where/got/want），而不是一句拼好的话。
///   而**级别由 e.cls 查表得出**，不由调用方给 —— 这正是"类别决定级别"。
void fail_api_misuse(const error_value& e);

/// 把 `error_value` 渲染成**规范文本**（与 `fail_*` 系列打印的那一句完全相同）。
///
/// 【为什么需要它 —— E10 的直接后果】
///   `wag.fail{level = record / warn}` 是"调用方**要求记一条**"，不是"引擎发现了错误"。
///   它的正确实现是按调用方要的**级别**写日志，而**不是**借 `fail_api_misuse`
///   （那是 L2 的兜底入口，E10 已把它赶出原语层）。
///   ⇒ 要把同一份文本按任意级别写出去，就得有一个"只渲染、不定级"的函数。
///
/// 【它也不该被别处拿来绕过级别】它只做字符串拼装，不写日志、不定级。
[[nodiscard]] std::string format_error(const error_value& e);

/// 报一条关闭序列里的错误。
///
/// 【它不弹窗】级别是 L1。
/// 【它的存在理由】关闭序列里没有"可带错继续"这一档 —— 那时回不到脚本，
///   所以只有"记下来，继续关"。
void fail_shutdown(std::string_view what);

// -----------------------------------------------------------------------------
//  终止前回调（2026-11-18 新增）
// -----------------------------------------------------------------------------

/// 注册一个"进程即将终止前"的回调（`nullptr` = 取消）。
///
/// 【它服务谁】`on_game_exit`：L4 终止时引擎仍然完整，是脚本"收尾"的最后机会。
///   `fail_boundary`（无落点）/ `fail_host` / `fail_internal` 三条终止路径都会调它。
///
/// 【为什么用回调而不是让 error 直接调 script】
///   `wag_error` 是最底层模块（`wag_script` 依赖它，反向不可以）。
///   ⇒ 与 `log::set_dialog_handler` 同一条理由：**依赖方向不能反过来**。
///
/// 【调用方必须保证】回调**幂等、不抛、不 longjmp**（它跑在要死的路径上）。
void set_before_terminate(void (*callback)()) noexcept;

// -----------------------------------------------------------------------------
//  校验辅助
//
//  【为什么校验要有一组辅助函数，而不是在每处写 if (!std::isfinite(x))】
//      因为已定的校验粒度是：**标量参数逐个查；结构化/数组参数在交界处整批
//      查一次**。把这套粒度写成一个函数，才能保证每一处的粒度一致。
// -----------------------------------------------------------------------------

/// 一个 double 是否是有限值（既不是 NaN 也不是无穷）。
///
/// 【为什么这不是多此一举】
///   对"坐标"这个语义而言，NaN 与无穷不是"少见的值"，而是**没有意义的值**
///   —— 它们不是引擎能够解释的输入。所以它们属于"数据互相矛盾"，属于必须
///   拒绝的那一类。
[[nodiscard]] bool is_finite(double v) noexcept;

/// 校验一组 double 全部有限。
///
/// @param values  指向一组 double 的指针
/// @param count   个数
/// @param where   出错时用于定位的名称前缀（例："顶点位置的 x"）
///
/// 【它在粒度上的位置】这是"结构化/数组参数整批查一次"那条的实现。
///   它要么全过（返回），要么报错并终止（fail_boundary 是 noreturn）。
void require_all_finite(const double* values,
                        std::size_t count,
                        std::string_view where);

} // namespace wag
