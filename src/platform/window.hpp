// -----------------------------------------------------------------------------
// window —— 唯一的一个窗口
// -----------------------------------------------------------------------------
class window {
public:
 /// 构造一个尚未创建的窗口。
 ///
 /// 【为什么允许"已构造但未创建"这个状态】
 /// 因为创建可能失败（平台拒绝、显示器不可用等），而失败必须能被表达。
 /// 于是"构造"与"创建"分成两步：构造不会失败，创建会。
    window() = default;

 /// 不可复制：一个窗口对应一份平台资源，复制会产生两个"同一个窗口"。
    window(const window&) = delete;
    window& operator=(const window&) = delete;

 /// 不可移动。
 ///
 /// 【理由】本类持有的资源（窗口、上下文）被交出之后由别的模块引用，
 /// 而"移走一个已经被引用的窗口"会让那些引用悬空。禁止移动是最省的
 /// 防错方式 —— 窗口在整个进程里只需要一个。
    window(window&&) = delete;
    window& operator=(window&&) = delete;

    ~window();

 // -------------------------------------------------------------------------
 // 创建与销毁
 // -------------------------------------------------------------------------

 /// 创建窗口，并**创建图形上下文**。
 ///
 /// @param w 期望的窗口宽度（窗口尺寸；不是 DIP）
 /// @param h 期望的窗口高度（窗口尺寸；不是 DIP）
 /// @param title 窗口标题（仅用于显示，引擎不解释它）
 /// @return 成功时返回 true
 ///
 /// 【注意 · 这里没有"是否可见"之类的参数】
 /// 那些属于"窗口选项"，而选项的集合尚未决策。等需要时再加 —— 加参数
 /// 是可以在不破坏调用点的情况下做的，而加语义不能。
 ///
 /// 【注意 · 这里没有"创建成功后上下文怎么取"这件事】
 /// 上下文由 take_gl_context() 单独交出，见下。
    bool create(double w, double h, const char* title);

 /// 销毁窗口。
 ///
 /// 【顺序要求】必须在图形上下文被销毁**之后**调用。
 /// 上下文依附于窗口，先销毁窗口会让上下文失去宿主。
 /// 这条顺序由关闭序列负责（见 wag/time/frame.hpp 的 shutdown_sequence）。
    void destroy();

 /// 是否已创建且尚未销毁。
    [[nodiscard]] bool is_created() const noexcept;

 /// **请求**把窗口客户区改成这个尺寸。
 ///
 /// @param w 宽，单位与"窗口尺寸"同一套（见下）
 /// @param h 高，同上
 /// @return 平台**接受**了这个请求时返回 true
 ///
 /// 【它是"请求"，不是"设定"—— 这条是整个设计的要点】
 /// 命令式：脚本请求一次，引擎申请一次，**不吸附、不纠正、不记住**。
 /// · 平台可能给不出来（屏幕不够大 / 系统约束 / 窗口在最大化状态）
 /// ⇒ 那时返回 false，由调用方记一条 **L2**（可降级，继续跑）
 /// · 引擎**不**替调用方改值（例如"自动吸附到最近的可用尺寸"）
 /// —— 那是决策，不是执行；引擎只把值变成动作
 ///
 /// 【单位：客户区的像素尺寸（与 get_pixel_size / get_window_size 同源）】
 /// 在这个平台上，SDL 创建、读取、设置三者使用同一单位；
 /// 本函数收的就是“窗口尺寸”那个量，不做任何换算。
 ///
 /// 【它不检查"是否与当前相同"】
 /// 去重是**引擎**的职责（见 engine 的 pending 窗口尺寸），因为只有引擎
 /// 知道"上一次应用的是什么"。平台层只负责把一次请求落地。
    bool set_size(double w, double h);

 // -------------------------------------------------------------------------
 // 图形上下文的交出（形态乙）
 // -------------------------------------------------------------------------

 /// 把图形上下文**交出**给调用方。
 ///
 /// @return 成功时返回一个有效的 gl_context；已经被交出过则返回 nullopt
 ///
 /// 【"交出"的确切含义】
 /// 调用之后，本 window 对象**不再持有**那个上下文（内部的句柄被清空）。
 /// 于是"窗口不再引用上下文"这条不变量由类型状态保证，而不是靠纪律。
 ///
 /// 【为什么允许失败】
 /// 重复交出是编程错误，但不是崩溃理由 —— 返回 nullopt 让调用方有机会
 /// 报出一条清楚的错误，而不是拿到一个悬空句柄。
 ///
 /// 【为什么只允许交出一次】
 /// 因为上下文只有一个所有者。允许交出两次就等于允许两个所有者，
 /// 而“两个所有者”正是内核一直要消掉的东西。
    std::optional<gl_context> take_gl_context();

 // -------------------------------------------------------------------------
 // 每帧的动作
 // -------------------------------------------------------------------------

 /// 换缓冲。
 ///
 /// 【它不做的事】不等垂直同步。垂直同步默认关闭，
 /// 因此本函数不阻塞。
    void present();

 /// 从平台取事件，写进内部的"事件位"。
 ///
 /// 【硬约束】本函数**绝不调用任何脚本**。
 /// 它只把"发生了什么事"的位记下来，真正的脚本调用发生在帧结构的
 /// 阶段 3（事件消费）。理由是：窗口消息路径可以在任意时刻被系统调用，
 /// 若它直接回调脚本，脚本就会在任意时刻重入引擎状态 —— 而那是崩溃的
 /// 经典来源，也是"引擎只用 13 个钩子回调脚本"这条封闭性被破坏的方式。
    void pump_events();

 /// 等"下一个事件"或"超时"，两者取先到的那个。
 ///
 /// @param timeout_ms 最长等待毫秒数；<= 0 表示"不等待，只抽一次队列"
 ///
 /// 【它为什么存在 —— 这一条修的是一个真实的症状】
 /// 帧率控制在阶段 2 要等一小段时间（例如 240 Hz 下约 4 ms）。若那段时间
 /// 用 `sleep` 过去，则**一条窗口消息都不被处理**；而它占了每帧的大部分
 /// 时间 ⇒ 系统会把这个窗口判成"未响应"（光标变成加载圈，拖动边框与
 /// 点标题栏都失效）。
 ///
 /// ⇒ 把"纯睡"换成"等消息或超时"之后：消息在整帧的空闲时间里都被处理,
 /// 窗口始终是活的；而它对帧率**没有影响**（等待的总时长不变）。
 ///
 /// 【它顺带更省 CPU】等消息比 `sleep` 更有效：没有消息时它真的在阻塞。
 ///
 /// 【与阶段 3 的分工 —— 三者不重叠】
 /// · `pump_events` / 本函数：只**泵**（把发生的事写进事件位）
 /// · 本函数另外负责**等**（空闲时间不再空转）
 /// · 阶段 3 只**消费**（读位、清位、据此回调钩子）
 /// ⇒ 所以本函数不会让"事件被消费两次"：它只写位，不读位。
 ///
 /// 【等待期间收到的事件怎么办】照常记进事件位（与 pump_events 同一套映射），
 /// 于是它们不会被丢掉，而是在本帧的阶段 3 被消费。
    void wait_events_or_timeout(int timeout_ms);

 /// 设置输入事件接收者（`nullptr` = 清除）。
 ///
 /// 【调用点】引擎启动序列（窗口创建之后）接上，关闭序列里先断掉。
 /// 【它做了什么额外的事】**播种鼠标初始位置**：
 /// 若此刻本窗口有焦点，用 `SDL_GetMouseState` 读一次并喂一条 mouse_move；
 /// 否则喂 (0,0) —— 不读，避免拿到别的窗口的坐标。
 /// 理由：在第一个真实 motion 之前，input 的鼠标位置不该是未初始化的 0,0
 /// （菜单会误判"鼠标在原点"）。
 /// 【硬约束不变】本函数只写数据；它不调用脚本。
 /// 【生命周期】window 必须比 sink 活得久；销毁前必须传 nullptr。
    void set_input_sink(input_sink* sink) noexcept;

 // -------------------------------------------------------------------------
 // 两个查询
 // -------------------------------------------------------------------------

 /// 窗口尺寸（window size）。
///
/// @return 平台当前报的窗口客户区尺寸；两个分量 >= 0；窗口最小化时可为 0
///
/// 【它不是 DIP】
/// 这是 `SDL_GetWindowSize` 的原样值，也是 `create` / `set_size` 接受的
/// 同一套“窗口尺寸”。当前 Windows 路径下它等于客户区像素；
/// 不要把它当作 DIP，也不要用 display_scale 去换算它。
///
/// 【不变量】
/// ① 单位是“窗口尺寸”，不是 DIP
/// ② **每次调用重新向平台取**，本对象不保存“上一次的值”
/// ③ 调用方**不得缓存**返回值
///
/// 【已实测：交互式拖动期间平台不更新这个尺寸】
/// frame=1 window=1920x1080 ← 启动
/// frame=2594 window=1920x1152 ← 拖下边界松手之后
/// frame=4109 window=2063x1152 ← 拖右边界松手之后
/// ⇒ Windows 的模态拖动循环期间，SDL 的窗口状态要等松手后才更新。
/// 这不是“读早一点”能解决的问题；拖动中的黑带是已知代价。
///
/// 【为什么不允许缓存】
/// 用户拖窗口、全屏切换、换显示器都会改它，而这些事情不经过引擎。
/// 长期缓存会产生脏副本，结果是画面错而不崩。
    [[nodiscard]] dimensions get_window_size() const;


 /// 绘制表面（帧缓冲）的像素尺寸。
///
/// @return `SDL_GetWindowSizeInPixels` 的原样值；平台报，不是算出来的
///
/// 【它不是“窗口尺寸 × 显示比例”】
/// 帧缓冲大小与视口位置都不经过 display_scale。
/// 当前平台（Windows、未启用高像素密度）窗口尺寸与像素尺寸相等；
/// 但**不要假设它们总是相等**：高像素密度下两者会不同。
///
/// 【它是渲染几何的唯一来源】
/// 渲染层用它设置 GL viewport / scissor 与帧缓冲尺寸；
/// 当它为 0 时退回窗口尺寸只是为了得到一个可计算的除数。
    [[nodiscard]] dimensions get_pixel_size() const;


 /// Windows UI 显示比例（150% = 1.5）。
///
/// @return 正实数；平台不支持时返回 1.0
///
/// 【它不是 DIP → 像素的换算因子】
/// 它来自 `SDL_GetWindowDisplayScale`，报的是 Windows 的 UI 缩放；
/// 不是“窗口尺寸 / 绘制表面尺寸”的比例。
/// 当前引擎**没有任何几何消费者**；它只放在 frame_geometry 里作诊断。
/// 拿它去乘窗口尺寸或除像素尺寸，都是错的。
///
/// 【不变量】
/// ① 正实数且有限
/// ② 每次调用重新向平台取，调用方不得缓存
/// ③ 取的是窗口所在显示器的 UI 缩放
    [[nodiscard]] double get_display_scale() const;


 // -------------------------------------------------------------------------
 // 本帧几何：三个量**一次读、一起走**（禁止用乘积互相推导）
 // -------------------------------------------------------------------------

 /// 一帧要用的全部几何，**同一次读取**地打包。
///
/// 【三个量是什么】
///   window        = 窗口尺寸（get_window_size）
///   pixel         = 绘制表面像素（get_pixel_size）
///   display_scale = Windows UI 显示比例（仅诊断）
///
/// 【为什么打包】
/// 分别调用三个 getter 允许在不同时刻读取；窗口恰好在两点之间变化时，
/// 就会得到一帧内两个瞬间的尺寸。打包后只能一起读、一起传。
///
/// 【不要混用】
/// 不要做 window × display_scale，也不要拿 pixel / display_scale 当窗口尺寸。
/// 当前平台两者相等只是因为未启用高像素密度，不是数学关系。
    struct frame_geometry {
 /// 窗口尺寸（`get_window_size()` 的原样值；不是 DIP）。
        dimensions window{};
 /// 绘制表面像素（`get_pixel_size()` 的原样值）。
        dimensions pixel{};
 /// Windows UI 显示比例（`get_display_scale()`；仅诊断，不参与几何）。
        double display_scale = 1.0;
    };

 /// 取本帧几何（**三个量一起**）。
///
/// 【为什么一次取】
/// 分别调 getter 允许窗口在两个读取点之间变化，得到一帧内两个瞬间的尺寸。
/// 一次取回保证 window / pixel / display_scale 都属于同一瞬间。
///
/// 【它不缓存】
/// 与三个 getter 一样：每次调用重新向平台取。
/// 可以每帧调一次，成本是三次读字段。
    [[nodiscard]] frame_geometry get_frame_geometry() const;

 // -------------------------------------------------------------------------
 // 输入与几何的唯一来源
 // -------------------------------------------------------------------------

 /// ⚠️【一条写下来的约定（不是代码，但必须在这里说）】
 ///
 /// · **窗口几何一律走 SDL 的尺寸 API**（本项目就是本类的两个 getter）。
 /// **不得**改用 Win32 的 `GetClientRect` / `GetWindowRect` 之类 ——
 /// 即使平台层“有权”用 Win32。
 /// 理由：多一个来源就多一个“两个真相”，而它们的差会表现成**内容偏一点**。
 ///
 /// · **输入坐标一律走 SDL 事件**（`mouse.x/y`、`SDL_GetMouseState` 之类），
 /// **不得**改用 `GetCursorPos` + `ScreenToClient`。
 /// 理由与上面相同，而且更硬：SDL 的事件坐标与 `SDL_GetWindowSize`
 /// **在同一坐标系**（已实测确认过两者相等），所以"输入 → 逻辑坐标"
 /// 这条路上**不需要任何 DPI 换算**。一旦换成 Win32 那条，就需要换算了，
 /// 而那个换算**本身就是错的**（见 `get_display_scale()` 的更正说明）。
 ///
 /// ⇒ 这两条都是本平台的硬约定；写在这里是因为**看代码的人先看到这里**。
    [[nodiscard]] static const char* geometry_source_convention() noexcept;

 // -------------------------------------------------------------------------
 // 事件位
 // -------------------------------------------------------------------------

 /// 读取并**清空**事件位。
 ///
 /// 【event_bits 为什么不在这个类里面 —— 这一条修的是一个真实的编译错误】
 /// 原先 `event_bits` 是**类内嵌套枚举**，于是：
 /// · 类内的成员函数能用裸名（`consume_events()` 的返回类型）✓
 /// · 而**类外**的代码不能用裸名 —— 必须写 `window::event_bits`
 /// ⇒ 下面那三个自由运算符（operator| / operator& / has_bit）
 /// 与 .cpp 里 `event_bits window::consume_events()` 的**定义**
 /// 都写在类外 ⇒ 于是它们看到的 `event_bits` **未声明**
 ///
 /// ⇒ 而更根本的是：**它本来就不该是嵌套类型。**
 /// 它表达的是"自上次消费以来发生了什么" —— 那是**帧结构**关心的东西,
 /// 而不是窗口的实现细节（它的唯一消费点就是阶段 3）。
 /// 把它放在命名空间作用域，既消除了可见性问题，也更符合它的语义。
 ///
 /// 【为什么用位集而不是回调或队列】
 /// 因为窗口消息路径只能"写一个标记"（见 pump_events 的硬约束）。位集
 /// 是这个约束下最省、也最不容易出错的形态：写位不会失败、不会阻塞、
 /// 也不会重入任何东西。
 ///
 /// 【为什么不是队列】
 /// 队列需要分配、需要生命周期管理，而"一帧内发生了两次同类事件"这件事
 /// 在语义上通常只需要知道"发生过"。需要细节的事件（键、鼠标）其数据由
 /// 输入采样统一提供，不从这里走。
 ///
 /// 【唯一调用点】帧结构的阶段 3。见 wag/time/frame.hpp。
    [[nodiscard]] event_bits consume_events();

 /// 窗口当前是否持有输入焦点（**状态**，不是事件）。
 ///
 /// 【为什么它必须与 event_bits 分开 —— 这一条是"事件 vs 状态"的区分】
 /// `consume_events()` 给的是"本帧发生过什么"（事件，取走即清零）；
 /// 而失焦之后的每一帧都仍然失焦，但**只有那一帧有 focus_lost 事件**。
 /// ⇒ 消费方若拿事件位来推状态，失焦的下一帧就会"自动恢复"
 /// （症状：暂停只闪一下）。
 /// ⇒ 所以焦点状态由 note_event 单独维护，读它是一个**状态查询**。
 ///
 /// 【初值 = true（"假设有焦点"）—— 这是一个刻意的取舍】
 /// 若初值取 false，那么"从控制台/脚本启动、尚未被用户点过"的应用
 /// 会**一启动就处于失焦暂停**（世界不跑、画面停在空帧），
 /// 而那不是"用户失焦"，是"还没获得"。
 /// ⇒ 取 true 的后果只是"真的从一开始就没焦点的窗口不会自动暂停"
 /// （与今天的行为一致，无回归）；一旦收到过一次 LOST/GAINED 就准确了。
    [[nodiscard]] bool has_focus() const noexcept { return focused_; }

private:
 // -------------------------------------------------------------------------
 // 内部状态
 //
 // 【为什么这些字段是私有的，而"引擎自身的全局状态"另有安排】
 // 本类是一个**实例**，它的字段不需要被别的模块看见 —— 别的模块只
 // 通过上面的公开接口与它交互。窗口是显式传下去的引擎实例成员之一，
 // 而不是一个全局。
 // -------------------------------------------------------------------------

 /// 平台窗口对象的句柄。由 create() 填，由 destroy() 清。
 /// 【不确定代码】具体类型取决于平台无关性方案（见类头的待定项）。
    void* native_handle_ = nullptr;

 /// 图形上下文的句柄。
 ///
 /// 【它在这里只是"待交出的东西"】
 /// 一旦 take_gl_context() 被调用，本字段被清空 —— 于是"窗口不再引用
 /// 上下文"这条不变量有代码上的保证，而不只是接口说明。
    gl_context ctx_{};

 /// 待消费的事件位。
    event_bits pending_events_ = event_bits::none;

 /// 窗口是否持有输入焦点（**状态**，由 note_event 在事件循环里维护）。
 /// 【初值 true 的理由】见 has_focus() 的说明（避免"启动即失焦暂停"）。
    bool focused_ = true;

 /// 输入事件接收者（不拥有；生命周期由引擎保证）。
 ///
 /// 【为什么是裸指针】它是"接线"，不是所有权；
 /// 所有权在 engine::impl（input 成员），窗口只借用。
    input_sink* input_sink_ = nullptr;
};

// -----------------------------------------------------------------------------
// event_bits 的位运算
//
// 【为什么需要手写】它是 enum class，默认不做位运算。写成自由函数是唯一
// 能在保持类型安全的同时做位运算的方式。
// -----------------------------------------------------------------------------

[[nodiscard]] constexpr event_bits operator|(event_bits a, event_bits b) noexcept {
    return static_cast<event_bits>(static_cast<std::uint32_t>(a) |
                                   static_cast<std::uint32_t>(b));
}

[[nodiscard]] constexpr event_bits operator&(event_bits a, event_bits b) noexcept {
    return static_cast<event_bits>(static_cast<std::uint32_t>(a) &
                                   static_cast<std::uint32_t>(b));
}

/// 就地置位。窗口消息路径用它累积事件位。
///
/// 【刻意不标 [[nodiscard]]】它不像 operator| 那样"只返回新值"，它的主要效果
/// 是副作用（改 a），返回值只支持链式写法。标了它，`a |= b;` 这种正常用法
/// 就会变成警告。
constexpr event_bits& operator|=(event_bits& a, event_bits b) noexcept {
    a = a | b;
    return a;
}

/// 检查某个位是否被置上。
[[nodiscard]] constexpr bool has_bit(event_bits set, event_bits bit) noexcept {
    return (set & bit) != event_bits::none;
}

