// =============================================================================
// wag/script/hook.hpp
//
// 内核：钩子协议。
//
// 【这一章是内核里最"协议档"的一块】
// 下面这 13 个名字一旦定下，改动它们会让所有脚本失效。因此：
//
// **每个名字只在这一处出现一次。**
//
// 引擎侧只有这一份清单（"白名单"），它与脚本侧 `wag.hook` 表上的槽名
// 一一对应。若名字在别处再写一遍，就会出现"同一个契约写两遍、而只有
// 一份是权威"的情形 —— 而那种分歧只在某个钩子"永远不被调用"时才暴露。
//
// 【为什么按名字查表，而不是让脚本注册函数指针】
// 因为脚本侧的表是**可写的普通表**（作者的代码要往里填），而引擎需要
// 一个不依赖"作者记得注册"的契约。按名查表还带来一个额外好处：
// 引擎在步骤 0 可以把 13 个槽预置成空函数，于是"调用时槽不是函数"
// 这件事在正常运行中几乎不可能发生。
//
// 【三个必须记住的性质】
// ① **全部无返回值** —— 引擎不读取它们的返回值，也不据此改变行为
// ② **实参是一个表** —— 见下面 frame_info 的注释
// ③ **取到非函数 ⇒ 引擎内部完整性错误** ⇒ C++ 侧路径，不得带错继续
// =============================================================================

#pragma once

#include <cstddef>
#include <cstdint>
#include <vector>

#include "platform/input_event.hpp"

namespace wag::time {
struct frame_state;
}

namespace wag::script {

class state;

// -----------------------------------------------------------------------------
// hook —— 13 个钩子
//
// 【计数为什么是 13 —— 它是自洽的】
//
// 6 时间线 × 相位 （main / pause / ext） × （帧 / 渲染）
// 2 帧内边界 begin / end
// 3 事件类 event / focus_gain / focus_lose
// 2 生命周期 game_init / game_exit
// ──
// 13
//
// 【构词法规则】on_ 前缀 + 全 snake_case + 同一构词法 + 全无返回值。
//
// 【一个容易误解的地方】
// "三个时段（main / pause / ext）与两个边界点（begin / end）"不是两种
// 含义 —— 边界点是时段退化后的情形（时段由两个边界点夹出）。而边界点
// 只存在于渲染相位：帧相位没有"边界"这一档。
// 这件事**不需要写进面向开发者的说明**：说明不声称那个乘法完备，
// 因此没人会去反推一个未被承诺的档。
//
// 【焦点为什么是两个槽】
// 引擎侧是两个槽（gain / lose），而**合并发生在映射层**：两个槽都接到
// 作者写的那一处分流函数上。于是作者只写一边，而引擎仍然数 13。
// 这也解释了"映射要合并一下"那句话 —— 合并是映射层的职责，不是引擎的。
// -----------------------------------------------------------------------------
enum class hook : std::uint8_t {
 /// **层装载完成后、帧循环之前一次**（2026-11-18 改定）。
 /// 此时**用户词汇已可用**；实参是**空表**；出错 ⇒ 终止级。
 /// 调用者是引导层（`init.lua` 步骤 5.7），不是引擎 ——
 /// 引擎不认识"层装载完成"这个时刻。
    on_game_init,

 /// 关闭序列**第 1 步**一次；**L4 终止前也调一次**（幂等）。
 /// **必须在任何资源被释放之前**被调用；实参是**空表**；出错 ⇒ L1（继续关）。
 /// **不保证被调用**（强杀、崩溃时没有机会）。
    on_game_exit,

 /// 每帧，逻辑相位，Ext 时间线。**先于主逻辑运行。**
    on_frame_ext,

 /// 仅正常帧，逻辑相位，Main 时间线。
    on_frame_main,

 /// 仅暂停帧，逻辑相位，Pause 时间线。
    on_frame_pause,

 /// 每帧，渲染相位，清屏之后、绘制任何内容之前。
 /// **绑定渲染目标与设置本帧渲染状态的唯一正当位置。**
    on_render_begin,

 /// 仅正常帧，渲染相位，场景绘制。
    on_render_main,

 /// 仅暂停帧，渲染相位。**引擎会先绘制冻结画面，再调用它。**
    on_render_pause,

 /// 每帧，渲染相位，**画在所有其它内容之上**。
    on_render_ext,

 /// 每帧，渲染相位，所有绘制完毕、呈现之前。
 /// **解绑渲染目标、后处理、截图的正当位置。**
    on_render_end,

 /// 有输入事件被消费时。
    on_event,

 /// 窗口获得焦点时。
    on_focus_gain,

 /// 窗口失去焦点时。
    on_focus_lose,
};

/// 钩子的个数。静态断言与遍历依赖它。
inline constexpr std::size_t hook_count = 13;

/// 把枚举转成协议名（即 `wag.hook` 表上的槽名）。
///
/// 【这是名字唯一被拼出来的地方】`hook_names` 表是引擎的"白名单"，
/// 也是脚本侧槽名的来源。不要在别处再写这些字符串。
[[nodiscard]] const char* hook_name(hook h) noexcept;

/// 全部协议名，按 hook 枚举顺序。
///
/// 【用途】
/// · 步骤 0 的预置（把每个槽设成空函数）
/// · 启动期自检（检查每个槽是不是函数）
///
/// 【为什么返回数组而不是让调用方遍历枚举】
/// 因为枚举的遍历在 C++ 里没有内建方式，而"逐个 static_cast"很容易漏一个。
/// 返回一张表，配合 hook_count，就不会漏。
[[nodiscard]] const char* const* all_hook_names() noexcept;

// -----------------------------------------------------------------------------
// frame_info —— 传给钩子的那个表里放什么
//
// 【表里只有三类东西】
// ① 本帧常量（dtg、frame、dragging、has_focus）
// ② 事件载荷（由 on_event 用；**每帧一批**，2026-11-16 起是数组表）
// ③ 焦点布尔（由 on_focus_* 用）
//
// ⇒ ② 只在 on_event 上有值（其它钩子上 `event` 为 nil）；
// ③ 在焦点钩子上有意义。① 是所有人都有的。
//
// 【为什么 ① 也放在表里，而不让脚本去查询】
// 理由不是方便，是**帧内一致性**：表在帧开始构造一次，全帧读到同一份值。
// 若改成"每次查询"，那么任何中途的改动都会让后面的钩子读到不同的值 ——
// 而"读到的必须是快照"这条在别处已经反复出现过。
// ⇒ 引擎也可以另外提供查询式接口，但两者**必须同源**。
//
// 【为什么用表而不是位置参数】
// 表意味着**将来增加字段不会破坏已有脚本**；而位置参数一旦增加就会
// 挤动所有已有参数的含义。这几个钩子的签名一旦定下就是协议档。
// -----------------------------------------------------------------------------
struct frame_info {
 /// 时间颗粒：**循环帧**的时长。
 ///
 /// 【名字为什么不是 dt】
 /// `dt` 在引擎实践里**已经被占用**了：它通常指"上一帧到这一帧过了多久"
 /// （真实的、可变的间隔）。而我们这里要指的是**一个锁死的常数** ——
 /// 两者含义相反 ⇒ 沿用 `dt` 会让每个读代码的人先理解错。
 /// ⇒ 用 `dtg`（delta time granule）：`g` 把"颗粒"钉在名字里。
 ///
 /// 【它的值：1/60 秒，已定】
 /// 5.2 明确："时间颗粒 = 1/60 秒（锁死）"，
 /// 且它是**项目级常数**（不可变）。
 ///
 /// 【它为什么必须锁死】doc 5.3：它是游戏时间的**网格**，也是调参、录像、
 /// 判定的**共同基准** ⇒ "基准不能动"。
 ///
 /// 【它不随什么变】不随窗口、不随目标帧率、不随机器性能。
 /// 慢落（机器来不及）与改目标帧率**都不改它** —— 变的是"每秒取几次颗粒"。
 ///
 /// 【⚠ 它数的是"循环帧"，不是"逻辑帧" —— 这一条很重要】
 /// 引擎**无法知道**脚本有没有真的推进逻辑（门控发生在钩体内部）。
 /// ⇒ 所以本字段代表的是"每跑一轮循环，时间前进一格"。
 /// ⇒ 而"游戏时间推进了多少"要由**脚本自己数它调了几次逻辑**。
 /// 这与"引擎不定义什么帧率算正常"是同一条立场；参见
 /// `frame` 字段的说明与5.4 那张表。
    double dtg = 1.0 / 60.0;

 /// 本帧的**循环帧号**。暂停帧不递增。
 ///
 /// 【为什么叫"循环帧号"而不是"逻辑帧号"】
 /// 因为它递增的判据是"这一轮循环跑了"，而**不是**"逻辑推进了"。
 /// 递增点在阶段 1（`if (mode == normal) ++frame_count`），早于任何钩子 ——
 /// 于是引擎不可能知道钩体里发生了什么。
 ///
 /// 【这带来的一个可观察后果】
 /// 若脚本用自己的计数器做门控（例如每 N 个循环帧才真正推进一次逻辑，
 /// 这是"慢放"的做法，见5.4），那么在被跳过的那几轮里，
 /// 钩子收到的 `frame` 是**同一个值**。
 /// ⇒ 也就是说：**帧号相同 ⇒ 这几轮属于同一个逻辑帧。**
 ///
 /// 【它与暂停的关系】暂停帧不递增 ⇒ 暂停期间它停住（与"暂停不推进逻辑时间"一致）。
    std::uint64_t frame = 0;

 /// 用户是否正在**交互式拖拽 / 缩放窗口**（2026-11-15）。
 ///
 /// 【它是什么】**本帧开始时**的状态快照，来自 `frame_state::dragging`，
 /// 而那个字段由阶段 1 从 `engine::window_sizemove()` 定格。
 ///
 /// 【"拖拽"包括什么】**拖动标题栏移动**与**拖拽边框缩放**都算。
 /// Windows 的 `WM_ENTERSIZEMOVE` 对两者是**同一条消息**，
 /// `WM_EXITSIZEMOVE` 一并结束 ⇒ 引擎无法在不引入"命中测试推断"的前提下区分
 /// （那会受不可见边框宽度与 DPI 影响，失败形态偶发）。
 /// ⇒ 想只处理缩放的脚本用"窗口尺寸有没有变"自己分；尺寸它本来就看得见。
 ///
 /// 【典型用法：拖拽即暂停】引擎**不**替你做这件事（`pause_source::drag`
 /// 保留但不点亮），但脚本可以：
 /// @code
 /// if info.dragging and not paused then wag.engine.pause() end
 /// @endcode
 /// 恢复必须显式（`wag.engine.resume()`），不靠"松手自动恢复"。
 /// WagLib 提供了一份默认策略，见其 `dragging` 相关模块。
 ///
 /// 【为什么是表字段而不是查询函数】表在帧开始构造一次、全帧读到同一份值
 /// （见上面"为什么 ① 也放在表里"）；查询式会让帧中途的翻转被看见，
 /// 且每调一次一次跨界。
    bool dragging = false;

 // ---- 以下字段只在事件类钩子上填充 ----

 /// 本帧收到的输入事件（**数组**，按发生顺序）；没有事件 ⇒ 空指针 ⇒ Lua 侧 `nil`。
 ///
 /// 【2026-11-16，】它原来是 `const void*`（lightuserdata，脚本读不到任何东西）。
 /// 现在改成真正的表：每个元素是
 /// `{ kind = "key_down" | "key_up" | "mouse_down" | "mouse_up"
 /// | "mouse_move" | "wheel",
 /// scancode = <整数，键事件>,
 /// button = <整数，鼠标键事件>,
 /// x, y = <逻辑坐标 DIP，鼠标事件>,
 /// dx, dy = <滚轮增量，滚轮事件> }`
 ///
 /// 【为什么是"每帧一批"而不是"每事件一次"】见：
 /// 帧内只应有一个快照；批量也让脚本能按顺序看到"这一帧先后发生了什么"。
    const std::vector<platform::input_event>* events = nullptr;

 /// 焦点状态（仅 on_focus_gain / on_focus_lose 相关时填）。
 ///
 /// 【为什么传布尔而不是"两个钩子各管一边就够"】
 /// 因为两个槽是引擎侧的形态（为了让计数保持 13），而脚本侧可能希望
 /// 只写一处分流。布尔让那一处分流成为可能。
    bool has_focus = false;
};

// -----------------------------------------------------------------------------
// 调用
// -----------------------------------------------------------------------------

/// 把帧状态转成传给钩子的那个表的内容。
///
/// 【为什么需要这一步转换，而不是直接把 frame_state 传进去】
/// 因为 frame_state 是**引擎的内部状态**，它含有的东西比脚本该看到的多了
/// 不少（休眠标志、暂存快照有效性、窗口尺寸快照、DPI 因子）。
/// 把整个 frame_state 交出去，就等于把"引擎当前在做什么"暴露给了脚本 ——
/// 而其中一些量（例如 DPI）在别处是刻意不暴露的。
///
/// ⇒ 于是这里做一次**收窄**：只把脚本该知道的三个量放进 frame_info。
/// 这是一条边界，而不是一次便利函数。
[[nodiscard]] frame_info make_frame_info(const time::frame_state& fs) noexcept;

/// 调用一个钩子。
///
/// @param st 脚本状态
/// @param h 要调用的钩子
/// @param fs 本帧状态（用于填充 frame_info）
///
/// 【它做什么】
/// ① 从 `wag.hook` 取 h 的协议名对应的槽
/// ② 若它不是函数 ⇒ **引擎内部完整性错误**（C++ 侧路径，不继续）
/// ③ 构造 frame_info 表并压栈
/// ④ pcall；脚本错误按"脚本自身的错"处理（L2，可继续）
///
/// 【为什么用 pcall 而不是 lua_call】
/// `lua_call` 会让错误以 longjmp 的形式穿过 C++ 帧 —— 那意味着 C++ 侧的
/// 析构函数可能不被调用。`lua_pcall` 是**唯一**把脚本错误挡回 C++ 的地方。
///
/// 【"可带错继续"的精确含义 —— 这一条容易含糊】
/// 它不是"继续执行那个出错的调用"（那个调用的行为是未定义的）。
/// 它指的是**继续推进帧结构** —— 后面的阶段照常走完。
/// 因为阶段之间的有序关系必须保住（阶段 10 必须在阶段 11 之前）。
/// ⇒ 引擎继续 ✓ ／ 脚本那一帧的行为 ✗
void call_hook(state& st, hook h, const time::frame_state& fs);

// -----------------------------------------------------------------------------
// call_hook_bare —— 给**生命周期钩子**用的、不需要帧状态的调用
// -----------------------------------------------------------------------------
//
/// 调一个"没有本帧"的钩子：**实参是空表**（`{}`）。
///
/// 【它服务谁】`on_game_init` / `on_game_exit`（2026-11-18 定）。
/// 那时没有 `frame_state`，而硬造 dtg/frame 会引入"启动时的帧号是多少"
/// 这种没人能答的问题 ⇒ 传空表，同时仍满足"实参是一个表"的契约。
///
/// 【出错怎么办】**L1**：只记日志（`log::record`），**不弹窗、不写 warn 行**。
/// 这对应"关闭序列里的错误只记日志，然后继续关"那条已定的行为。
/// 注意它**不同于** `call_hook` 的 L2 —— 生命周期钩子没有"继续推进帧结构"
/// 这回事，只有"继续关"。
///
/// 【它保证不发生的事】不抛异常、不 longjmp（内部走 `lua_pcall`）。
void call_hook_bare(state& st, hook h) noexcept;

/// 调 `on_game_exit`，**全进程只调一次**（幂等）。
///
/// 【为什么要幂等】两条路径都会调它：①正常关闭序列的第 1 步；②L4 终止之前。
/// L4 可能发生在关闭序列中途（例如步骤 2/3 出错）⇒ 不设防就会调两次，
/// 而"退出又开始、开始又退出"是脚本最容易写出依赖顺序错乱的地方。
///
/// @return 本次是否真的调用了（false = 之前已调过，或脚本状态不存在）
bool call_exit_hook_once(state& st) noexcept;

} // namespace wag::script
