// =============================================================================
// wag/time/frame.hpp
//
// 内核：帧结构与帧级可变状态。
//
// 【这一章解决什么】
// 它把帧级时序固定成一套结构：
//
// · 12 个阶段的固定顺序
// · 帧级可变状态（**团一**）收成一个结构体
// · 阶段 1 的四件事
// · 窗口尺寸为 0 时的休眠
// · 状态切换在阶段 11
//
// 【为什么帧级状态要收成一个结构体，而不是散在引擎实例里】
// 两条理由：
// ① 一个参数解决签名爆炸
// ② 它与"读到的必须是快照"**天然一致** —— 帧结构体就是那个快照的载体
//
// 而第三条理由在代码上更明显：**它让阶段约束变成代码形状**。
// "某些字段只在阶段 1 写、某些从阶段 7 起才被填"这件事，在一个结构体
// 里是可以看出来的；散在全局里则退化成约定。
// =============================================================================

#pragma once

#include "engine/engine.hpp"
#include "platform/input_event.hpp"
#include "space/rect.hpp"

#include <cstdint>
#include <vector>

// 【命名空间】原 `wag::core`，现为 `wag::time`（1.2："帧、时间线、
// 随机流"）。engine / engine_state 在外层 `wag::`，本命名空间内可直接用短名。
// 变更记录见 log/log.hpp 文件头。
namespace wag::time {

// -----------------------------------------------------------------------------
// frame_mode —— 本帧的形态
//
// 【它是快照，不是活状态】
// 在阶段 1 由 engine_state 取一次，此后整帧不变。
//
// 【为什么必须这样】
// 因为"按下暂停的那一帧"必须仍然完整地按 Main 运行。若渲染分支读活状态,
// 那一帧的世界渲染会被整体跳过 —— 而玩家看到的就是"上一帧的画面 +
// 暂停菜单"，那不对。
//
// 【它与 engine_state 的值域相同但不是同一个类型】
// 刻意分成两个类型：这样"把活状态传进渲染分支"会是一个编译错误，
// 而不是一个需要靠纪律避免的写法。
// -----------------------------------------------------------------------------
enum class frame_mode {
 /// 正常帧：跑 Main 的逻辑与渲染。
    normal,

 /// 暂停帧：跑 Pause 的逻辑与渲染。
    paused,
};

[[nodiscard]] const char* mode_name(frame_mode m) noexcept;

// -----------------------------------------------------------------------------
// stage —— 12 个阶段
//
// 【为什么阶段号是一个枚举而不是注释里的编号】
// 因为报错信息需要它（"调用点：哪个钩子、哪一帧"），而"当前在哪个阶段"
// 是引擎**本来就知道**的东西。把它做成一个字段，报错就能自己补上上下文,
// 不需要每个报错点手工传。（见 wag/log/log.hpp 的 format）
//
// 【顺序不可变】阶段之间的有序关系是内核的一部分，例如"阶段 10 必须在
// 阶段 11 之前"。这也是"可带错继续"只意味着"继续推进帧结构"的原因。
// -----------------------------------------------------------------------------
enum class stage : std::uint8_t {
 /// 阶段 1：帧开始。
 /// 做四件事：定 frame_mode、递增 frame_count、取窗口尺寸与显示比例快照、
 /// 算本帧变换。**休眠判定也在这里。**
    frame_begin = 1,

 /// 阶段 2：帧率控制。
 /// 决定"这一帧什么时候开始"。**不属于渲染管线，因此休眠时照常运行。**
    rate_control = 2,

 /// 阶段 3：事件消费。
 /// 消费窗口事件位，并把真正的脚本调用集中在这里。
 /// **休眠时必须继续** —— 否则恢复事件收不到，会永远休眠。
    event_consume = 3,

 /// 阶段 4：输入采样。**无条件执行**（与状态无关，暂停时也要采）。
    input_sample = 4,

 /// 阶段 5：Ext 逻辑。
    ext_logic = 5,

 /// 阶段 6：主逻辑（Main 或 Pause，由 frame_mode 决定）。
    main_logic = 6,

 /// 阶段 7：渲染开始（清屏）。**休眠时跳过。**
    render_begin = 7,

 /// 阶段 8：场景渲染。**休眠时跳过。**
    scene_render = 8,

 /// 阶段 9：Ext 渲染与收尾。**休眠时跳过。**
    ext_render_and_finish = 9,

 /// 阶段 10：帧快照（暂存）。**休眠时必须跳过** —— 见下面 frame_state
 /// 里 staged_snapshot_valid 的注释。
    snapshot = 10,

 /// 阶段 11：状态切换与帧末结算。
 /// **休眠时继续，但只做状态切换。**
    state_apply = 11,

 /// 阶段 12：呈现。**休眠时跳过。**
    present = 12,
};

[[nodiscard]] const char* stage_name(stage s) noexcept;

// -----------------------------------------------------------------------------
// frame_state —— 帧级可变状态（团一）
//
// 【生命周期】每帧在阶段 1 被重置/填充，在阶段 12 之后失效。
// 【它不拥有任何资源】全部是值。因此它没有生命周期问题，也不需要清理。
//
// 【为什么不做成"引擎实例的成员"】
// 因为它每帧重建。把它与长驻状态混在一起会让"哪些字段跨帧存在"变得
// 看不出来，而那正是最容易出错的分类。
// -----------------------------------------------------------------------------
struct frame_state {
 // -------------------------------------------------------------------------
 // 阶段 1 填充的四个量
 // -------------------------------------------------------------------------

 /// 本帧的形态。
 ///
 /// 【写入时机】**只在阶段 1**。此后整帧只读。
 /// 【它是快照】见 frame_mode 的注释。
    frame_mode mode = frame_mode::normal;

 /// 本帧的**循环帧号**。
 ///
 /// 【递增规则（已定）】**只在阶段 1、且只在 mode == normal 时 +1。**
 /// 于是：
 /// · 暂停不推进（暂停期间它停住）
 /// · 全帧（含所有钩子）读到一致的帧号
 ///
 /// 【⚠ 它是"循环帧号"，不是"逻辑帧号"】
 /// 递增在阶段 1、**早于任何钩子** ⇒ 引擎不可能知道钩体里有没有真的推进逻辑。
 /// 而脚本可以用自己的计数器门控逻辑（例如每 N 个循环帧才推进一次，
 /// 那是"慢放"的做法，见5.4）——
 /// 那种情形下，被跳过的几轮**看到同一个帧号**。
 /// ⇒ 所以"帧号相同"的含义是：**这几轮属于同一个逻辑帧。**
 ///
 /// 【为什么不做成"逻辑帧号"】
 /// 因为那要求引擎知道脚本的意图，而"逻辑推进几次"是**脚本侧的决策**
 /// （与"引擎不定义什么帧率算正常"同一条立场）。
 ///
 /// 【它是 uint64 而不是 int】因为它单调递增且不应回绕。选择 64 位是为了
 /// 让"回绕"这件事在可预见的未来不成为一个需要考虑的情形。
    std::uint64_t frame_count = 0;

 /// 本帧读到的窗口尺寸快照。单位是“窗口尺寸”，不是 DIP。
 ///
 /// 【为什么是快照】窗口尺寸是"外部会改、而渲染要用"的量（用户拖窗口、
 /// 全屏切换、换显示器都会改它），而那些事情都不经过引擎。
 /// 在阶段 1 取一次，本帧就不再读活值。
 ///
 /// 【已知行为】若窗口尺寸在本帧中途被改变（阶段 3 消费到 resized），
 /// 本帧的映射仍用这个旧尺寸，而渲染目标是新尺寸 ⇒ 那一帧的画面按旧尺寸
 /// 映射一次，看起来像"晚一帧才调整好"。这是**已接受**的行为，不修。
    space::rect window_size{};

 /// 本帧的几何：**三个量一次读**（窗口尺寸 / 绘制表面像素 / 显示比例）。
 ///
 /// 【为什么整包存在这里，而不只是窗口尺寸】
 /// 有一条硬约定：**禁止用 `窗口尺寸 × display_scale` 互相推导**
 /// （见 `platform/window.hpp` 头部）。而"分别去调三个 getter"这件事本身
 /// 就在给"自己凑一个"留机会 —— 更糟的是，分别调还允许**在不同时刻**调：
 /// 阶段 1 读窗口尺寸、阶段 7 读像素，而窗口恰好在这两点之间变了 ⇒
 /// **一帧内两个瞬间的尺寸**（实测事实 15）。
 /// ⇒ 所以在阶段 1 **一次性**取回整包，本帧后面所有地方都只读它。
 /// ⇒ 顺带把下面那条"已知行为"收紧了：`window_size` 仍是本帧的快照，
 /// 而像素尺寸从此**也**是同一个瞬间的快照。
 ///
 /// ⚠️【为什么这里是"三个扁平的数"而不是 `window::frame_geometry`】
 /// 因为本头文件的定位是不依赖平台层（它只含 `space/rect.hpp`）。
 /// 若为了一个整数快照把 `platform/window.hpp` 拖进来，就等于让**内核的
 /// 帧状态**依赖平台实现 —— 而内核边界那条纪律正是"不知道 SDL3、不知道 GL"。
 /// ⇒ 于是这里存扁平值，而在**唯一的使用点**（阶段 7）把它们装成
 /// `platform::window::frame_geometry` 传给渲染层。
 /// ⇒ ⚠️ 代价说清：**"三个量一起读"这条约束在类型上没有被强制**，
 /// 它靠的是"阶段 1 只取一次、后面只读快照"这条纪律。
 /// （真正的类型级强制需要带单位的类型，取舍见。）
    struct {
 /// 窗口尺寸（不是 DIP）。
        double window_w = 0.0;
        double window_h = 0.0;
 /// 绘制表面像素（平台报的，**不是** `window_size × display_scale`）。
        double pixel_w = 0.0;
        double pixel_h = 0.0;
 /// Windows UI 显示比例（`get_display_scale()`）。**仅作诊断**，不参与渲染几何。
        double display_scale = 1.0;
    } geom{};

 /// 本帧读到的 Windows UI 显示比例（仅诊断，不是几何换算因子）。
 ///
 /// ⚠️【更正：它现在**没有消费方** —— 已实测】
 /// 这里曾写着"DPI 只在渲染阶段被用来把 DIP 换算成物理像素"。**那是错的**：
 /// 窗口几何的尺寸 API 本来就报物理像素；输入坐标与窗口尺寸**在同一坐标系**
 /// （SDL3 事件），所以两处都不需要换算。
 /// ⇒ 它（`SDL_GetWindowDisplayScale`）报的是 **Windows 的 UI 缩放**，
 /// **不是**"物理/逻辑比例" ⇒ **在任何一处拿它做几何换算都是错的**。
 /// ⇒ 📌 最终处置是**删除**。现在保留只为不在某一步同时改变行为；
 /// 它与 `geom.display_scale` 是同一个值（后者是正式来源）。
 /// ⇒ 依据：第四、五节与清单第 10 条。
    double display_scale = 1.0;

 // -------------------------------------------------------------------------
 // 休眠
 // -------------------------------------------------------------------------

 /// 本帧是否休眠了整条渲染管线。
 ///
 /// 【判定点：阶段 1】用 window_size 的**矩形有效性**来判，而不是某个
 /// "尺寸为空"的方法 —— 因为 window_size 的类型是 space::rect
 /// （它由窗口上报的 dimensions 的两个分量构造而来）。
 /// 两者语义等价：rect 的 w/h 不可能为负（它们来自 >= 0 的分量），
 /// 所以 `!is_valid()` 就是"存在一个分量为 0"。
 /// 在阶段 1 判定的好处有两条：
 /// ① **那条除以窗口尺寸的除法根本不会执行** —— 比"算了之后检查
 /// inf/NaN"干净
 /// ② 整帧行为一致，不会出现"前半帧不休眠、后半帧休眠"
 ///
 /// 【休眠的范围】跳阶段 7、8、9、10、12；继续阶段 1~6 与 11 的状态切换。
 /// **阶段 3 必须继续**（否则恢复事件收不到，会永远休眠）。
    bool pipeline_asleep = false;

 // -------------------------------------------------------------------------
 // 窗口交互状态（2026-11-15）
 // -------------------------------------------------------------------------

 /// 本帧开始时，用户是否正在**交互式拖拽 / 缩放**窗口。
 ///
 /// 【写入时机】**只在阶段 1**，取自 `engine::window_sizemove()`。
 /// 此后整帧只读 ⇒ 与 `mode` / `frame_count` 同一条纪律：帧内一个值。
 ///
 /// 【为什么要它进 `frame_state`】因为它要经过 `make_frame_info()` 收窄成
 /// `frame_info::dragging` 交给脚本。表在帧开始构造一次、全帧读到同一份值
 /// —— 若改成"让脚本每次去查询"，帧中途的翻转会让同一个帧里两个钩子
 /// 读到不同的值（`hook.hpp` 里 `frame_info` 的注释讲的就是这件事）。
 ///
 /// 【"拖拽"包括什么】**拖动标题栏移动**与**拖拽边框缩放**都算 ——
 /// Windows 的 `WM_ENTERSIZEMOVE` 对两者是同一条消息，引擎无法也不该区分。
    bool dragging = false;

 /// 本帧开始时窗口是否**有焦点**。
 ///
 /// 【写入时机】只在阶段 1。与 `dragging` 同一条纪律：帧内一个值。
 /// 【它喂给谁】`frame_info::has_focus`（13 个钩子都拿得到）。
    bool has_focus = false;

 /// 本帧的输入事件批次。
 ///
 /// 【什么时候设】阶段 4 采样之后指向 `input::frame_events()`；
 /// **阶段 3 的焦点钩子之前它是 nullptr** —— 那时本帧还没采样，
 /// 给上一帧的批次只会更糟。
 /// 【生存期】指向 input 内部的向量，本帧内有效（下一帧 sample 会换掉）。
    const std::vector<platform::input_event>* events = nullptr;

 // -------------------------------------------------------------------------
 // 快照（阶段 10 / 11）
 // -------------------------------------------------------------------------

 /// 暂存快照是否已经有一份有效内容。
 ///
 /// 【为什么需要这个标志 —— 这是内核里一个具体的缺陷的修法】
 /// 若休眠时仍然更新暂存快照，那么：
 /// 最小化时清屏对着一个 0×0 的目标 ⇒ **快照被清空**
 /// ⇒ 下一帧若恢复并进入暂停 ⇒ 冻结画面是**空的**
 ///
 /// 所以**阶段 10 在休眠时必须跳过**，而这个标志记录"当前暂存的这一份
 /// 是不是有效内容"。它使下面这条成为可能：
 /// · 阶段 11 的 frozen_snapshot = staged_snapshot 照常执行
 /// · 而它取到的仍是**最后一张有效渲染结果**
 ///
 /// 【为什么不需要"失效"机制】因为恢复后的第一帧会正常渲染，阶段 10 会
 /// 自动刷新它。
    bool staged_snapshot_valid = false;

 // -------------------------------------------------------------------------
 // 报错上下文
 // -------------------------------------------------------------------------

 /// 当前正在执行的钩子名（用于错误信息）。
 ///
 /// 【为什么它在帧状态里】因为它是"当前在哪个阶段 / 哪个钩子"这一组
 /// 上下文的一半，而报错模块需要它来补全错误信息。引擎在调用钩子之前
 /// 写入、调用之后清空。
 ///
 /// 【它为什么不是一个索引】因为报错信息要显示名字。存指针不分配。
    const char* current_hook = nullptr;
};

// -----------------------------------------------------------------------------
// frame_pipeline —— 12 阶段的驱动
//
// 【它是一个 struct 而不是一组自由函数】
// 因为它持有"本帧的状态"，而那正是帧结构体的意义：显式传递。
// 使用方式是：构造一个，然后 run_one_frame()。
//
// 【它是 engine 的 friend】
// 因为阶段 11 需要应用 engine 的 pending 状态，而那个操作不该是公开 API。
// -----------------------------------------------------------------------------
struct frame_pipeline {
 /// 本帧的可变状态。
 ///
 /// 【公开的理由】它是"显式传递"的那一团东西，而不是需要隐藏的内部。
 /// 引擎的其它部分（钩子调用点、报错模块）需要读它。
    frame_state fs{};

 /// 跑一帧：依次执行 12 个阶段。
 ///
 /// @param eng 引擎实例
 ///
 /// 【它不返回"是否该继续"】
 /// 退出的判断在帧末由调用方做（读 engine 的 exit 请求）。让本函数返回
 /// 一个 bool 会把"退出"变成第二个信号源。
 ///
 /// 【它不再"等"】（2026-11-14，见下面的 wait_until_next_due）
 /// 阶段 2 只做节拍记账；**等待与泵事件已经移出本函数**。
    void run_one_frame(engine& eng);

 /// 等到"下一帧应当开始的时刻"，期间**泵窗口事件**（2026-11-14 搬出帧外）。
 ///
 /// 【为什么它必须在 run_one_frame 之外】
 /// 这段等待里唯一会阻塞的就是 `SDL_WaitEventTimeout`，而**窗口拖拽的模态循环
 /// 恰恰会在那里把控制权拿走**（Windows 在自己的循环里跑，WM_PAINT 仍会到）。
 /// 只要这段等待还在 `run_one_frame` 内部，任何"从消息路径补跑一帧"的尝试都是
 /// **重入 12 阶段管线**。搬出来之后，消息路径才有资格跑帧（第二步再启用）。
 ///
 /// 【它还要做的一件事：每帧必泵一次】
 /// 搬之前只有"需要等"的帧才泵事件（落后帧完全不泵，事件会积压）。
 /// 这里**不等也要泵一次**，于是"每帧恰好泵一次"成立。
 ///
 /// 【调用形状（main 的循环）】
 /// @code
 /// while (true) {
 /// pipeline.wait_until_next_due(eng); // 等 + 泵
 /// pipeline.run_one_frame(eng); // 12 阶段（阶段 3 消费刚泵到的事件）
 /// if (eng.exit_requested()) break;
 /// }
 /// @endcode
    void wait_until_next_due(engine& eng);

 /// 当前是否正在跑一帧（**重入守卫**，2026-11-14）。
 ///
 /// 【为什么需要它】`run_one_frame` 将有两个入口：主循环、以及（第二步）消息路径
 /// 里的补跑。漏一处守卫的后果是栈递归 / 状态撕裂 —— 偶发且难复现。
 /// 所有入口都必须过这里。
    [[nodiscard]] bool in_frame() const noexcept { return in_frame_; }

 /// 现在是否**到了**下一帧该开始的时刻（动态拖拽用，2026-11-14）。
 ///
 /// 【为什么拖拽期间必须用它门控】拖拽时没有主循环去等，帧只能由消息路径补跑；
 /// 而消息是 OS 推的、密度不受我们控制 ⇒ 必须自己掐"到点才跑"。
 /// **不睡**：模态循环里睡一帧等于错过 WM_PAINT 的节奏，拖拽会一顿一顿。
 /// ⇒ 这是"同一条限速"在一个人为稀疏的节拍源下的唯一可行形态。
 ///
 /// 【没有 due（首帧 / 目标变更 / 目标非法）⇒ false】不知道节拍就别补跑。
    [[nodiscard]] bool frame_due() const noexcept;

 /// 是否已经有一条时间线（即 `next_due_ns_ > 0`）。
 ///
 /// 【它和 `frame_due()` 的区别】**首帧没有 due，但主循环仍然要跑第一帧。**
 /// ⇒ 主循环的条件是 `!has_next_due() || frame_due()`；
 /// 而拖拽补跑的条件只有 `frame_due()`（没 due 就不补）。
    [[nodiscard]] bool has_next_due() const noexcept { return next_due_ns_ > 0.0; }

private:
 // -------------------------------------------------------------------------
 // 逐个阶段
 //
 // 【为什么每个阶段一个私有函数，即使它只有两行】
 // 因为阶段是内核的规格单位：它们的顺序、它们的读/写集合、它们是否
 // 在休眠时运行，都是规格的一部分。写成独立函数之后，"某个阶段做了
 // 不属于它的事"会更容易被发现。
 // -------------------------------------------------------------------------

 /// 阶段 1：帧开始。
    void stage_frame_begin(engine& eng);

 /// 阶段 2：帧率控制。
    void stage_rate_control(engine& eng);

 /// 阶段 3：事件消费。
    void stage_event_consume(engine& eng);

 /// 阶段 4：输入采样。
    void stage_input_sample(engine& eng);

 /// 阶段 5：Ext 逻辑。
    void stage_ext_logic(engine& eng);

 /// 阶段 6：主逻辑。
    void stage_main_logic(engine& eng);

 /// 阶段 7：渲染开始。
    void stage_render_begin(engine& eng);

 /// 阶段 8：场景渲染。
    void stage_scene_render(engine& eng);

 /// 阶段 9：Ext 渲染与收尾。
    void stage_ext_render_and_finish(engine& eng);

 /// 阶段 10：帧快照。
    void stage_snapshot(engine& eng);

 /// 阶段 11：状态切换与帧末结算。
    void stage_state_apply(engine& eng);

 /// 阶段 12：呈现。
    void stage_present(engine& eng);

 // -------------------------------------------------------------------------
 // 帧率控制器的状态（只属于阶段 2）
 // -------------------------------------------------------------------------

 /// 上一帧读到的目标帧率。
 ///
 /// 【为什么需要它】已定的睡觉判据是"目标帧率的**值与上一帧不同**"（而不是
 /// "被调用了"）。没有这个值就无法判断"值有没有变"。
 ///
 /// 【初值 0.0 的含义】"还没有过基准"⇒ 第一帧必然走"重设基准"那一支。
    double last_target_fps_ = 0.0;

 /// 时间基准（本帧间隔恒定这条假设的起点），单位纳秒。
 ///
 /// 【目标帧率变化时它被重设】因为"目标恒定"是长期纠偏的前提。
    long long rate_epoch_ns_ = 0;

 /// 基准以来的**节拍数** —— 节拍器的自计数，每次"等时刻"消费一格。
 ///
 /// 【节拍器的基准必须独立于 frame_count】
 /// frame_count 只在 normal 帧递增；暂停期间它不推进，而真实时间继续走。
 /// 所以节拍器用独立的 `rate_ticks_`，每次进入本阶段消费一格：
 ///   · 暂停期间循环照常每格等一次，不空转；
 ///   · 恢复时 due 就在眼前，不会爆发式追赶；
 ///   · 游戏时间仍由 frame_count 决定，暂停时逻辑照常冻结。
 ///
 /// 【它是有意与 frame_count 不同的量】frame_count 是逻辑时间线
 /// （暂停不推进），本计数是真实时间线（只要循环在跑就推进）。
 ///
 /// 【机器抖动/加载卡顿】一帧真长了 ⇒ due 落到过去 ⇒ 后续帧不等，
 /// 直到追上时间线。加载卡顿会被控制器追赶一次，这是已接受的行为。
    std::uint64_t rate_ticks_ = 0;

 /// "下一帧应当开始的时刻"（steady 纳秒）。**0 = 不等待**（首帧 / 目标变更 / 目标非法）。
 ///
 /// 【为什么由阶段 2 算、由帧外等】阶段 2 仍拥有节拍记账（`rate_ticks_` 与基准），
 /// 但**等待**已经搬出 `run_one_frame`（见 `wait_until_next_due`）。
 /// 阶段 2 在这里留下"下一帧该在何时开始"，帧外的等待读它。
 ///
 /// 【为什么是 +1 个间隔】阶段 2 在**本帧已经开始之后**才跑，
 /// 所以它对"本帧的 due"已经无能为力；它算的是**下一帧**的 due。
    double next_due_ns_ = 0.0;

 /// 重入守卫：`run_one_frame` 的两次进入是不可想象的，见 `in_frame()`。
    bool in_frame_ = false;

 // -------------------------------------------------------------------------
 // 帧率读数（每秒一行）
 // -------------------------------------------------------------------------

 /// 上一次统计的时间起点（纳秒）。0 表示还没有起点。
    long long stat_epoch_ns_ = 0;

 /// 自起点以来跑过的帧数。
    std::uint64_t stat_frames_ = 0;

 // -------------------------------------------------------------------------
 // 渲染统计的**每秒累加器**（2026-11-14 起，计数器归 perf_log 独占）
 //
 // 【为什么要有它们】perf_log 逐帧取走 `take_draw_stats()`，而每秒一行的
 // 帧率报告仍要"这一秒的提交数/顶点数/图元数" ⇒ 逐帧取、这里累加，
 // 1 Hz 时读累加值再清零。
 //
 // 【E 已裁决（2026-11-14）】计数器归 perf_log **独占**：它逐帧 `take_draw_stats()`，
 // 这里负责累加，1 Hz 时读累加值再清零。
 // 没选 `peek_draw_stats()`（不清零）是因为 `take` 会把基线清零，
 // peek 再算差分就会崩 —— **一份基线**才靠得住。
    std::uint64_t acc_submissions_ = 0;
    std::uint64_t acc_flushes_ = 0;
    std::uint64_t acc_vertices_ = 0;
    std::uint64_t acc_primitives_ = 0;

 /// perf_log 撞到 64 MB 上限的那条日志是否已经打过（只打一次）。
    bool perf_cap_logged_ = false;
};

} // namespace wag::time
